//! `tokenpack` — a static-vocabulary token codec for short text.
//!
//! Why not deflate: a chat message is 20–200 bytes. Deflate has nothing to
//! match against yet and pays for a Huffman table (or the fixed one's poor
//! fit), so on that size it usually *expands* — snapclone-wirecodec measured
//! this and simply refused to compress under 64 bytes. zstd with a trained
//! dictionary fixes it but drags in a C library and a dictionary blob.
//!
//! This codec moves the "dictionary" into a static vocabulary of ~4k byte
//! strings (learned by byte-level BPE from a corpus) and a canonical Huffman
//! code over them. Every single byte is in the vocabulary, so any input is
//! encodable; common English fragments (` the`, `ing`, ` you`) cost 5–9 bits,
//! a rare byte costs up to 20. There is no header: the stream is codes until
//! an end-of-stream token. A 20-byte message costs ~9 bytes.
//!
//! Two parsers share one decoder: [`Parse::Greedy`] takes the longest token
//! at each position (one trie walk per token); [`Parse::Optimal`] runs a
//! min-bits dynamic programme over the whole input (a reversed-token trie
//! walk per position) and is 2–4% smaller. Both are deterministic.
//!
//! The vocabulary lives in `vocab_data.rs`, generated by
//! `tools/train_vocab.py` — rerun it on a better corpus (real chat history,
//! more French) and only that file changes.

mod vocab_data;

use crate::huffman::{BitReader, BitWriter, Code};
use std::sync::OnceLock;

pub use vocab_data::{EOS, MAX_CODE_LEN, MAX_TOKEN_LEN, N_TOKENS};

/// Which parser the encoder uses. The decoder does not care.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Parse {
    /// Longest match at each position. Fast, ~3% off optimal.
    Greedy,
    /// Minimum-bits parse (DP). Default: still microseconds for a message.
    #[default]
    Optimal,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// The bits ran out before an end-of-stream token.
    Truncated,
    /// A code did not resolve to a token within `MAX_CODE_LEN` bits.
    BadCode,
    /// Output would exceed the caller's limit.
    TooLong,
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Truncated => write!(f, "tokenpack: truncated stream (no EOS)"),
            Error::BadCode => write!(f, "tokenpack: invalid code"),
            Error::TooLong => write!(f, "tokenpack: output exceeds limit"),
        }
    }
}
impl std::error::Error for Error {}

// ── trie ─────────────────────────────────────────────────────────────────────

const NO_TOKEN: u16 = u16::MAX;

#[derive(Clone, Copy)]
struct Node {
    token: u16,       // token ending at this node, or NO_TOKEN
    first_child: u32, // index into `edges`
    n_children: u16,
}

/// A byte trie over the vocabulary. `reversed = true` stores each token
/// backwards so a walk from position `k` toward the start finds every token
/// that *ends* at `k` — exactly what the forward DP needs.
struct Trie {
    nodes: Vec<Node>,
    edges: Vec<(u8, u32)>, // (byte, child) sorted by byte within a node
}

impl Trie {
    fn build(reversed: bool) -> Trie {
        // temporary children maps, then flatten
        let mut tok: Vec<u16> = vec![NO_TOKEN];
        let mut kids: Vec<Vec<(u8, u32)>> = vec![Vec::new()];
        for (i, (bytes, _)) in vocab_data::VOCAB.iter().enumerate() {
            if bytes.is_empty() {
                continue; // EOS has no bytes
            }
            let mut cur = 0usize;
            let it: Box<dyn Iterator<Item = &u8>> = if reversed {
                Box::new(bytes.iter().rev())
            } else {
                Box::new(bytes.iter())
            };
            for &b in it {
                let next = match kids[cur].iter().find(|(kb, _)| *kb == b) {
                    Some(&(_, n)) => n as usize,
                    None => {
                        let n = tok.len();
                        tok.push(NO_TOKEN);
                        kids.push(Vec::new());
                        kids[cur].push((b, n as u32));
                        n
                    }
                };
                cur = next;
            }
            tok[cur] = i as u16;
        }
        let mut nodes = Vec::with_capacity(tok.len());
        let mut edges = Vec::new();
        for (i, k) in kids.iter_mut().enumerate() {
            k.sort_by_key(|e| e.0);
            nodes.push(Node { token: tok[i], first_child: edges.len() as u32, n_children: k.len() as u16 });
            edges.extend_from_slice(k);
        }
        Trie { nodes, edges }
    }

    #[inline]
    fn child(&self, node: u32, b: u8) -> Option<u32> {
        let n = self.nodes[node as usize];
        let s = n.first_child as usize;
        let e = s + n.n_children as usize;
        let slice = &self.edges[s..e];
        // nodes are small; linear scan beats binary search below ~16 children
        if slice.len() <= 16 {
            slice.iter().find(|(kb, _)| *kb == b).map(|&(_, c)| c)
        } else {
            slice.binary_search_by_key(&b, |e| e.0).ok().map(|i| slice[i].1)
        }
    }
}

struct Model {
    code: Code,
    fwd: Trie,
    rev: Trie,
}

fn model() -> &'static Model {
    static M: OnceLock<Model> = OnceLock::new();
    M.get_or_init(|| {
        let lens: Vec<u8> = vocab_data::VOCAB.iter().map(|(_, l)| *l).collect();
        Model { code: Code::from_lengths(&lens), fwd: Trie::build(false), rev: Trie::build(true) }
    })
}

/// Bytes of a token.
#[inline]
pub fn token_bytes(t: u16) -> &'static [u8] {
    vocab_data::VOCAB[t as usize].0
}

/// Code length in bits of a token.
#[inline]
pub fn token_bits(t: u16) -> u8 {
    vocab_data::VOCAB[t as usize].1
}

// ── parsing ──────────────────────────────────────────────────────────────────

/// Greedy longest-match tokenisation. Every byte is a token, so this never
/// fails.
pub fn parse_greedy(input: &[u8]) -> Vec<u16> {
    let m = model();
    let mut out = Vec::with_capacity(input.len() / 3 + 1);
    let mut i = 0;
    while i < input.len() {
        let mut node = 0u32;
        let mut best = (input[i] as u16, 1usize); // the byte literal always matches
        let end = (i + MAX_TOKEN_LEN).min(input.len());
        for (k, &b) in input[i..end].iter().enumerate() {
            match m.fwd.child(node, b) {
                Some(c) => {
                    node = c;
                    let t = m.fwd.nodes[c as usize].token;
                    if t != NO_TOKEN {
                        best = (t, k + 1);
                    }
                }
                None => break,
            }
        }
        out.push(best.0);
        i += best.1;
    }
    out
}

/// Forward min-bits DP: `cost[k]` = fewest bits to encode `input[..k]`,
/// `back[k]` = token that ends at `k` in that parse. Shared by the optimal
/// encoder and by [`fit`], which needs every prefix's cost.
fn dp(input: &[u8]) -> (Vec<u32>, Vec<u16>) {
    let m = model();
    let n = input.len();
    let mut cost = vec![u32::MAX; n + 1];
    let mut back = vec![NO_TOKEN; n + 1];
    cost[0] = 0;
    for k in 1..=n {
        let mut node = 0u32;
        let mut best = u32::MAX;
        let mut best_t = NO_TOKEN;
        // walk backwards from k-1 through the reversed trie
        let lo = k.saturating_sub(MAX_TOKEN_LEN);
        for j in (lo..k).rev() {
            match m.rev.child(node, input[j]) {
                Some(c) => {
                    node = c;
                    let t = m.rev.nodes[c as usize].token;
                    if t != NO_TOKEN && cost[j] != u32::MAX {
                        let c2 = cost[j] + token_bits(t) as u32;
                        if c2 < best {
                            best = c2;
                            best_t = t;
                        }
                    }
                }
                None => break,
            }
        }
        debug_assert!(best_t != NO_TOKEN, "byte literals guarantee a match");
        cost[k] = best;
        back[k] = best_t;
    }
    (cost, back)
}

/// Minimum-bits tokenisation.
pub fn parse_optimal(input: &[u8]) -> Vec<u16> {
    let (_, back) = dp(input);
    let mut toks = Vec::new();
    let mut k = input.len();
    while k > 0 {
        let t = back[k];
        toks.push(t);
        k -= token_bytes(t).len();
    }
    toks.reverse();
    toks
}

pub fn parse(input: &[u8], how: Parse) -> Vec<u16> {
    match how {
        Parse::Greedy => parse_greedy(input),
        Parse::Optimal => parse_optimal(input),
    }
}

// ── codec ────────────────────────────────────────────────────────────────────

/// Bits the encoded stream will take (including EOS), without allocating the
/// output.
pub fn encoded_bits(input: &[u8], how: Parse) -> usize {
    parse(input, how).iter().map(|&t| token_bits(t) as usize).sum::<usize>() + token_bits(EOS) as usize
}

/// Encode. Output length is `ceil(encoded_bits / 8)`; at least one byte (EOS).
pub fn encode(input: &[u8], how: Parse) -> Vec<u8> {
    let m = model();
    let mut w = BitWriter::new();
    for t in parse(input, how) {
        let (c, l) = m.code.codes[t as usize];
        w.write(c, l);
    }
    let (c, l) = m.code.codes[EOS as usize];
    w.write(c, l);
    w.finish()
}

/// Worst-case decoded bytes per encoded byte: the longest token divided by
/// the shortest code. Lets a caller size a buffer before decoding.
pub fn max_expansion() -> usize {
    let min_bits = vocab_data::VOCAB.iter().filter(|(b, _)| !b.is_empty()).map(|(_, l)| *l).min().unwrap_or(1) as usize;
    (MAX_TOKEN_LEN * 8).div_ceil(min_bits)
}

/// Decode until EOS. Bits after EOS are ignored.
pub fn decode(wire: &[u8]) -> Result<Vec<u8>, Error> {
    decode_limited(wire, usize::MAX)
}

/// Decode with an output cap; fails with [`Error::TooLong`] instead of
/// allocating past it.
pub fn decode_limited(wire: &[u8], max_out: usize) -> Result<Vec<u8>, Error> {
    let m = model();
    let mut r = BitReader::new(wire);
    let mut out = Vec::with_capacity((wire.len() * 3).min(max_out));
    loop {
        let t = match m.code.decode(&mut r) {
            Some(t) => t,
            None => {
                return Err(if r.bits_left() == 0 { Error::Truncated } else { Error::BadCode });
            }
        };
        if t == EOS {
            return Ok(out);
        }
        let b = token_bytes(t);
        if out.len() + b.len() > max_out {
            return Err(Error::TooLong);
        }
        out.extend_from_slice(b);
    }
}

/// Result of [`fit`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Fit {
    /// Bytes of input included (a UTF-8 char boundary when `input` is text).
    pub bytes_in: usize,
    /// Encoded stream, `<= budget` bytes.
    pub wire: Vec<u8>,
}

/// Longest prefix of `input` whose encoding fits in `budget` bytes, using the
/// optimal parse. If `input` is valid UTF-8 the cut lands on a char boundary
/// so the decoded prefix is still valid text.
pub fn fit(input: &[u8], budget: usize) -> Fit {
    let (cost, back) = dp(input);
    let limit = budget.saturating_mul(8);
    let eos = token_bits(EOS) as usize;
    let utf8 = std::str::from_utf8(input).is_ok();
    let mut k = input.len();
    loop {
        let ok = cost[k] != u32::MAX && cost[k] as usize + eos <= limit && (!utf8 || is_char_boundary(input, k));
        if ok || k == 0 {
            break;
        }
        k -= 1;
    }
    // rebuild the parse of input[..k] from the DP back-pointers
    let m = model();
    let mut toks = Vec::new();
    let mut j = k;
    while j > 0 {
        let t = back[j];
        toks.push(t);
        j -= token_bytes(t).len();
    }
    let mut w = BitWriter::new();
    for &t in toks.iter().rev() {
        let (c, l) = m.code.codes[t as usize];
        w.write(c, l);
    }
    let (c, l) = m.code.codes[EOS as usize];
    w.write(c, l);
    let wire = w.finish();
    debug_assert!(wire.len() <= budget.max(1));
    Fit { bytes_in: k, wire }
}

#[inline]
fn is_char_boundary(s: &[u8], k: usize) -> bool {
    k == 0 || k == s.len() || (s[k] as i8) >= -0x40
}

#[cfg(test)]
mod tests {
    use super::*;

    const CHAT: &[&str] = &[
        "hey are you around? need to ask you something quick",
        "omw, traffic is terrible on the bridge",
        "je suis en route, le trafic est terrible sur le pont",
        "happy anniversary to us!",
        "",
        "a",
        "\u{1F600}\u{1F600} emoji only",
        "https://example.com/a/very/long/path?with=querystring&and=more",
    ];

    #[test]
    fn roundtrip_chat_both_parsers() {
        for s in CHAT {
            for how in [Parse::Greedy, Parse::Optimal] {
                let w = encode(s.as_bytes(), how);
                assert_eq!(decode(&w).unwrap(), s.as_bytes(), "{s:?} {how:?}");
                assert_eq!(w.len(), encoded_bits(s.as_bytes(), how).div_ceil(8));
            }
        }
    }

    #[test]
    fn roundtrip_every_byte_value_and_random_binary() {
        let all: Vec<u8> = (0..=255u8).collect();
        assert_eq!(decode(&encode(&all, Parse::Optimal)).unwrap(), all);
        let mut s = 0x9E3779B97F4A7C15u64;
        let random: Vec<u8> = (0..3000)
            .map(|_| {
                s ^= s << 13;
                s ^= s >> 7;
                s ^= s << 17;
                (s >> 24) as u8
            })
            .collect();
        let w = encode(&random, Parse::Optimal);
        assert_eq!(decode(&w).unwrap(), random);
        // random bytes cost more than raw, and the caller's "never expand"
        // fallback is what handles that — but not absurdly more:
        assert!(w.len() < random.len() * 3, "{} vs {}", w.len(), random.len());
    }

    #[test]
    fn optimal_never_beaten_by_greedy() {
        let mut worse = 0;
        for s in CHAT {
            let g = encoded_bits(s.as_bytes(), Parse::Greedy);
            let o = encoded_bits(s.as_bytes(), Parse::Optimal);
            assert!(o <= g, "{s:?}: optimal {o} > greedy {g}");
            if o < g {
                worse += 1;
            }
        }
        assert!(worse >= 1, "optimal parse never found a shorter parse than greedy on any sample");
    }

    #[test]
    fn short_english_beats_raw_by_2x() {
        let s = b"hey are you around? need to ask you something quick";
        let w = encode(s, Parse::Optimal);
        assert!(w.len() * 2 <= s.len(), "{} vs {}", w.len(), s.len());
    }

    #[test]
    fn truncated_and_garbage_never_panic() {
        let s = b"the quick brown fox jumps over the lazy dog";
        let w = encode(s, Parse::Optimal);
        for cut in 0..w.len() {
            match decode(&w[..cut]) {
                Ok(v) => assert!(v.len() < s.len()), // padding happened to decode; fine, but not the full message
                Err(_) => {}
            }
        }
        let mut x = 0xDEADBEEFu32;
        for _ in 0..500 {
            let mut g = vec![0u8; (x % 40) as usize];
            for b in g.iter_mut() {
                x = x.wrapping_mul(1664525).wrapping_add(1013904223);
                *b = (x >> 24) as u8;
            }
            let _ = decode_limited(&g, 4096);
        }
        assert_eq!(decode(&[]), Err(Error::Truncated));
    }

    #[test]
    fn decode_limit_is_enforced() {
        let s = b"the the the the the the the the the the the the";
        let w = encode(s, Parse::Optimal);
        assert_eq!(decode_limited(&w, 10), Err(Error::TooLong));
        assert_eq!(decode_limited(&w, s.len()).unwrap(), s);
        // the advertised bound really bounds
        assert!(s.len() <= w.len() * max_expansion());
    }

    #[test]
    fn fit_returns_longest_prefix_under_budget_on_char_boundary() {
        let text = "café au lait, s'il vous plaît — et un croissant. ".repeat(40);
        for budget in [1usize, 4, 16, 64, 144, 504, 752] {
            let f = fit(text.as_bytes(), budget);
            assert!(f.wire.len() <= budget, "budget {budget}: {} bytes", f.wire.len());
            assert!(text.is_char_boundary(f.bytes_in));
            assert_eq!(decode(&f.wire).unwrap(), &text.as_bytes()[..f.bytes_in]);
            // one more char would not fit (or we took everything)
            if f.bytes_in < text.len() {
                let mut nk = f.bytes_in + 1;
                while !text.is_char_boundary(nk) {
                    nk += 1;
                }
                assert!(encode(&text.as_bytes()[..nk], Parse::Optimal).len() > budget, "budget {budget} not tight");
            }
        }
        assert_eq!(fit(b"", 1).bytes_in, 0);
        assert_eq!(fit(b"abc", 0).wire.len(), 1); // budget 0 still yields the 1-byte EOS stream
    }

    /// Cross-check against the Python trainer's encoder: same vocab, same
    /// canonical assignment, same optimal parse.
    #[test]
    fn matches_python_test_vectors() {
        let vecs = include_str!("../../testdata/tokenpack_vectors.txt");
        let mut n = 0;
        for line in vecs.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (a, b) = line.split_once(' ').unwrap();
            let input = unhex(a);
            let want = unhex(b);
            assert_eq!(encode(&input, Parse::Optimal), want, "encode {:?}", String::from_utf8_lossy(&input));
            assert_eq!(decode(&want).unwrap(), input);
            n += 1;
        }
        assert!(n >= 20, "vector file is too small to mean anything ({n})");
    }

    fn unhex(s: &str) -> Vec<u8> {
        if s == "-" {
            return Vec::new();
        }
        (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
    }
}
