//! Key model: the data describing one individual key on the keyboard.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Key {
    /// The label as drawn in the lowercase / Normal state.
    pub label: String,

    /// The label as drawn in the Shifted / CapsLock state. Defaults to
    /// `label.to_uppercase()` when missing.
    #[serde(default)]
    pub shifted: Option<String>,

    /// What the key emits.
    #[serde(default)]
    pub action: KeyAction,

    /// What category of key this is (used for special rendering).
    #[serde(default)]
    pub key_type: KeyType,

    /// Long-press popup characters (lowercase variants).
    #[serde(default)]
    pub extended: Vec<String>,

    /// Long-press popup characters (uppercase variants).
    #[serde(default)]
    pub extended_shifted: Vec<String>,

    /// Width relative to one "unit" — 1.0 is a normal letter key. The space
    /// bar is typically 5.0; shift, return, etc. are 1.5.
    #[serde(default = "default_width")]
    pub width: f32,

    /// True when this key shouldn't be skipped over by swipe gestures (i.e.
    /// it represents an actual letter, not a modifier).
    #[serde(default = "default_swipe_target")]
    pub swipe_target: bool,

    /// Per-direction gesture outputs for cardinal-grid layout style.
    /// `None` for standard layouts. When `Some`, the key supports
    /// tap (uses `label`/`action`) plus the gestures defined here.
    #[serde(default)]
    pub gestures: Option<KeyGestures>,

    /// Optional extra CSS class applied to the rendered KeyWidget, in
    /// addition to the standard widget classes. Layout-authors can
    /// attach this to give a specific key a distinctive look (e.g.
    /// the "arcade-buffer" thin keys flanking the Dvorak spacebar)
    /// without baking the visual treatment into the global stylesheet.
    /// `None` (the default) means no extra class — the key renders
    /// with the standard `.key-button` styling only.
    #[serde(default)]
    pub extra_css_class: Option<String>,
}

/// Per-key gesture-to-character mapping for cardinal-grid layouts.
/// Each direction is the lowercase output; uppercase variants are
/// generated by the hairpin gesture in the same direction.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct KeyGestures {
    /// North: swipe up from key center.
    #[serde(default)]
    pub n: Option<String>,
    /// Northeast: swipe up-right.
    #[serde(default)]
    pub ne: Option<String>,
    /// East: swipe right.
    #[serde(default)]
    pub e: Option<String>,
    /// Southeast.
    #[serde(default)]
    pub se: Option<String>,
    /// South.
    #[serde(default)]
    pub s: Option<String>,
    /// Southwest.
    #[serde(default)]
    pub sw: Option<String>,
    /// West.
    #[serde(default)]
    pub w: Option<String>,
    /// Northwest.
    #[serde(default)]
    pub nw: Option<String>,
    /// Clockwise rotation gesture output (typically a digit).
    #[serde(default)]
    pub cw: Option<String>,
    /// Counter-clockwise rotation gesture output.
    #[serde(default)]
    pub ccw: Option<String>,
}

fn default_width() -> f32 {
    1.0
}
fn default_swipe_target() -> bool {
    true
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum KeyAction {
    /// Emit a character (the key's `label` or `shifted` value).
    Character,
    /// Emit an explicit string regardless of shift state.
    Literal(String),
    /// Backspace.
    Backspace,
    /// Return / enter.
    Return,
    /// Spacebar.
    Space,
    /// Tab.
    Tab,
    /// Toggle the shift state.
    Shift,
    /// Toggle symbols/letters page.
    SymbolsToggle,
    /// Switch to numbers page.
    Numbers,
    /// Switch to emoji page.
    Emoji,
    /// Activate voice input.
    Voice,
    /// Switch input language.
    LanguageSwitch,
    /// Hide the keyboard.
    HideKeyboard,
    /// Send a literal keysym (e.g. arrow keys).
    Keysym(String),
    /// Open the in-keyboard settings panel (replaces the keyboard view
    /// with a config UI for switching layouts/row-styles/etc).
    Settings,
    /// Visible-but-inert key — used as a layout spacer in rows that
    /// need a placeholder cell. Tapping commits nothing; swipes
    /// through are ignored.
    NoOp,
    /// Undo the most recent text commit. The engine pops its undo
    /// stack and emits BackSpace for each character.
    Undo,
    /// Open the LLM prompt UI on the microterm. Tapping this key
    /// is equivalent to opening the inline prompt entry on the
    /// microterm where the user types or speaks an instruction.
    Llm,
    /// Switch from the focus-tray (arrow-keys-only) layout back to
    /// the full keyboard. Only meaningful when the keyboard is in
    /// tray mode (focus_show_tray=true and showing the arrow-keys
    /// layout). On regular layouts this is a no-op.
    ShowFullKeyboard,
    /// One of the four steno buttons. The string identifies which:
    /// "L1" (left-outer), "L2" (left-inner), "R1" (right-inner),
    /// "R2" (right-outer). Gestures on this key (tap + N/E/S/W
    /// swipes) feed the steno engine which pairs them across the
    /// two thumbs and looks up the resulting pair-stroke in the
    /// phoneme/brief table.
    Steno(String),
    /// Cycle the code-mode for the cardinal-grid-words layout:
    /// Prose → C → Rust → Python → Prose. The engine emits this
    /// action; the UI listener cycles the `code_mode::CODE_MODE`
    /// atomic and rebuilds the current layout so the word cells
    /// re-render with the new mode's templates.
    CodeLangCycle,
}

impl Default for KeyAction {
    fn default() -> Self {
        KeyAction::Character
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum KeyType {
    /// Standard letter / symbol.
    Normal,
    /// Modifier (shift, ctrl, etc.) — colored differently.
    Modifier,
    /// Action (return, backspace) — colored differently.
    Action,
    /// Special function (voice, emoji, etc.).
    Special,
}

impl Default for KeyType {
    fn default() -> Self {
        KeyType::Normal
    }
}

impl Key {
    pub fn character(label: impl Into<String>) -> Self {
        let label = label.into();
        let shifted = label.to_uppercase();
        Self {
            label,
            shifted: Some(shifted),
            action: KeyAction::Character,
            key_type: KeyType::Normal,
            extended: vec![],
            extended_shifted: vec![],
            width: 1.0,
            swipe_target: true,
            gestures: None,
            extra_css_class: None,
        }
    }

    pub fn special(label: impl Into<String>, action: KeyAction) -> Self {
        Self {
            label: label.into(),
            shifted: None,
            action,
            key_type: KeyType::Special,
            extended: vec![],
            extended_shifted: vec![],
            width: 1.0,
            swipe_target: false,
            gestures: None,
            extra_css_class: None,
        }
    }

    pub fn modifier(label: impl Into<String>, action: KeyAction) -> Self {
        Self {
            label: label.into(),
            shifted: None,
            action,
            key_type: KeyType::Modifier,
            extended: vec![],
            extended_shifted: vec![],
            width: 1.5,
            swipe_target: false,
            gestures: None,
            extra_css_class: None,
        }
    }

    pub fn with_width(mut self, width: f32) -> Self {
        self.width = width;
        self
    }

    /// Attach an additional CSS class to the key (e.g. "arcade-buffer"
    /// for the thin spacebar-flanking keys). The class is applied by
    /// `KeyWidget::new` on top of the standard widget classes; styling
    /// must be defined in `resources/styles/keyboard.css`.
    pub fn with_css_class(mut self, class: impl Into<String>) -> Self {
        self.extra_css_class = Some(class.into());
        self
    }

    pub fn with_extended(mut self, extended: Vec<String>) -> Self {
        self.extended = extended;
        self
    }

    /// Attach cardinal-grid gesture outputs to this key. Only meaningful
    /// when the parent `Layout` has `style: CardinalGrid`.
    pub fn with_gestures(mut self, gestures: KeyGestures) -> Self {
        self.gestures = Some(gestures);
        self
    }

    /// Compute the displayed label for the current shift state.
    pub fn display_label(&self, shifted: bool) -> &str {
        if shifted {
            self.shifted.as_deref().unwrap_or(&self.label)
        } else {
            &self.label
        }
    }

    /// Compute the character to emit on press.
    pub fn emit_char(&self, shifted: bool) -> Option<String> {
        match &self.action {
            KeyAction::Character => Some(self.display_label(shifted).to_string()),
            KeyAction::Literal(s) => {
                // Literal honors shift by capitalizing the first
                // character. This lets word cells ("the ", "and ",
                // etc.) Title-case themselves at sentence start —
                // auto_cap sets the keypad to Shifted, the cell emits
                // "The " instead of "the ". Empty literals pass
                // through unchanged. Multi-char shifts only touch
                // the first grapheme, preserving the rest verbatim
                // (so a code template like "fn " stays "fn ", not
                // "Fn " — code never enters with shifted=true unless
                // the user manually held shift).
                if shifted && !s.is_empty() {
                    let mut chars = s.chars();
                    let first = chars.next().unwrap();
                    // to_uppercase() returns an iterator since some
                    // chars map to multi-char uppercase (ß → SS). We
                    // collect that prefix, then append the rest.
                    let mut out: String = first.to_uppercase().collect();
                    out.push_str(chars.as_str());
                    Some(out)
                } else {
                    Some(s.clone())
                }
            }
            KeyAction::Space => Some(" ".to_string()),
            KeyAction::Tab => Some("\t".to_string()),
            KeyAction::Return => Some("\n".to_string()),
            _ => None,
        }
    }

    /// Categorize this key into one of the four touch-behavior types
    /// the gesture dispatcher recognizes. Derived from existing key
    /// properties — no extra config needed in layouts.
    ///
    /// The four behaviors are:
    ///
    /// - **Normal**: standard tap. Press highlights, release-inside
    ///   commits, drag-off cancels. The default for letter keys with
    ///   no per-direction `gestures` and no swipe-source flag.
    ///
    /// - **Cardinal**: NESW + diagonal swipes plus clock-oriented
    ///   multi-region swipes for digits/symbols. Used by every key
    ///   in a cardinal-grid layout that has a `gestures` map. On
    ///   release, the cardinal dispatcher decides whether the path
    ///   matches a cardinal direction, a hairpin (return-to-start),
    ///   a clock rotation (for digits), or aborts.
    ///
    ///   "Clock rotation" requires the path to pass through a set of
    ///   regions in a specific order (e.g. N → NE → E → SE for a CW
    ///   90° arc that means "the digit 1"), and at release the start
    ///   point must be reasonably close to the end if it was a full
    ///   360° loop (true hairpin). If those conditions aren't met
    ///   the gesture aborts — no character is committed.
    ///
    /// - **AltKeySwipe**: a key where a one-cell-traversal swipe in
    ///   a dominantly-cardinal direction picks an alt-character
    ///   (e.g. swipe-down on a letter for its number row equivalent
    ///   on iOS-style keyboards). On release, if the path went
    ///   approximately one cell in N/E/S/W direction, the alt-key
    ///   for that direction is committed AND the parent gesture is
    ///   told to suppress any swipe-typing fallback. This is how a
    ///   key with `extended` characters can be reached without a
    ///   long-press popover.
    ///
    /// - **SwipeSource**: pressing the key starts swipe-typing
    ///   immediately rather than waiting for the swipe to leave a
    ///   key region. The spacebar in springboard mode is the
    ///   canonical example — drag from space and the recognizer
    ///   begins assembling a word right away.
    pub fn behavior(&self) -> ButtonBehavior {
        match &self.action {
            // Space is the springboard / swipe-typing source.
            KeyAction::Space => ButtonBehavior::SwipeSource,
            // Steno keys use cardinal behavior so the same swipe
            // dispatcher fires; the keyboard_view intercept
            // routes steno-key swipes into the steno engine
            // instead of committing them as text directly.
            KeyAction::Steno(_) => ButtonBehavior::Cardinal,
            // Character keys with explicit per-direction gestures
            // are cardinal-grid cells.
            KeyAction::Character if self.gestures.is_some() => ButtonBehavior::Cardinal,
            // Keysym keys with explicit per-direction gestures act
            // as joystick-style directional pads. Swiping a direction
            // emits the corresponding keysym from the gestures map.
            // Used by the arrows tray's central key to cluster the
            // four arrow keysyms onto one widget — swipe N/E/S/W
            // to send Up/Right/Down/Left without lifting the finger.
            KeyAction::Keysym(_) if self.gestures.is_some() => ButtonBehavior::Cardinal,
            // Letters with extended alt-characters that we want
            // reachable via one-cell swipe (configurable in future;
            // for now we conservatively keep this off by default to
            // avoid regressing the iOS-style flick gesture into
            // something users haven't opted into).
            KeyAction::Character if !self.extended.is_empty() => {
                // Currently treated as Normal; uncomment to enable
                // alt-key-swipe globally:
                // ButtonBehavior::AltKeySwipe
                ButtonBehavior::Normal
            }
            // Everything else (modifiers, specials, regular letters
            // without gestures) → Normal tap.
            _ => ButtonBehavior::Normal,
        }
    }
}

/// Touch-and-release behavior categories. See `Key::behavior` for the
/// full rationale; in short, this is how the gesture dispatcher
/// decides what a press-and-release sequence means for each key.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ButtonBehavior {
    /// Standard tap key. Press highlights, release-inside commits.
    Normal,
    /// Cardinal-grid cell with per-direction gestures + clock
    /// rotations + hairpin (return-to-start for capitalization).
    Cardinal,
    /// One-cell directional swipe picks an alt-character, AND
    /// signals the parent gesture to suppress swipe-typing.
    AltKeySwipe,
    /// Touching this key starts swipe-typing immediately. The
    /// spacebar in springboard mode.
    SwipeSource,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn character_key_uppercases() {
        let k = Key::character("a");
        assert_eq!(k.display_label(false), "a");
        assert_eq!(k.display_label(true), "A");
    }

    #[test]
    fn space_emits_space_regardless_of_shift() {
        let k = Key::special(" ", KeyAction::Space);
        assert_eq!(k.emit_char(false).as_deref(), Some(" "));
        assert_eq!(k.emit_char(true).as_deref(), Some(" "));
    }

    #[test]
    fn shift_key_emits_no_char() {
        let k = Key::modifier("⇧", KeyAction::Shift);
        assert!(k.emit_char(false).is_none());
    }
}
