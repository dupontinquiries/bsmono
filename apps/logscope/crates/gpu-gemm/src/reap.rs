//! reap.rs — killing a branch before it finishes, and whether that actually buys anything.
//!
//! I claimed early termination converts into more concurrent hypotheses. Checking that against the
//! allocator turned it into a narrower claim, and the narrowing is the useful part.
//!
//! ## Early kill and the bump arena are in tension
//!
//! The generational design is a bump cursor over a KV arena with no free list, reset at the round
//! boundary — the search provides the garbage collection. That is the right call and it is exactly
//! what makes a mid-round kill worthless: a dead branch's pages are a HOLE below the cursor, and a
//! bump allocator cannot reuse a hole. Killing branch 7 at token 40 frees nothing that anything can
//! allocate from until the round ends and the cursor resets.
//!
//! Three ways out, and they are not equally good:
//!
//! * **A page free list.** Reclaims exactly what died. Reintroduces the fragmentation and
//!   synchronisation the bump arena existed to avoid, and on a GPU that is a real cost.
//! * **Compaction on kill.** Moves live pages down. Copies KV, which is the one thing that must stay
//!   cheap; a compaction that copies a survivor's 8k-token cache to reclaim a dead branch's 300
//!   tokens has lost the trade.
//! * **Fixed per-branch slots.** Reserve `slot_pages` per slot up front. A dead branch's SLOT is
//!   immediately reusable by a fork with no allocator work at all, because the reservation never
//!   moved. Costs internal fragmentation: a branch that dies at 300 tokens wasted a slot sized for
//!   its budget.
//!
//! Slots are the one that keeps the arena dumb, so this module is written in slots. It is the same
//! move as the round-level "top-keep, drop N" policy, applied one level down.
//!
//! ## The number that decides whether it is worth it
//!
//! A slot's YIELD is hypotheses started per slot per round. Without early kill it is exactly 1: a
//! branch occupies its slot for the whole round whether it died at token 20 or ran to budget. With
//! early kill at mean fraction `f` of the budget, a slot turns over roughly `1/f` times — so killing
//! doomed branches a fifth of the way in is a 5× increase in hypotheses per slot, at no extra KV.
//!
//! That is a much bigger lever than anything in `steer.rs`, and it needs no model changes. It is
//! also entirely gated on the detector: a check that fires on 5% of branches cannot deliver it, and
//! one that false-kills good branches is buying throughput with solutions.
//!
//! Pure: no wgpu, no allocator.

/// A cheap check that can condemn a branch mid-generation, ordered by cost.
///
/// The ordering is the design. Anything that requires a compile is not a kill check — it is the
/// evaluator, and by the time it runs the branch has already spent its slot.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum KillCause {
    /// Generated past its token budget without terminating.
    Budget,
    /// Output cannot be a prefix of anything well-formed (unbalanced delimiters that can no longer
    /// close, a fence that never opened). Cheap, syntactic, and never wrong when it fires.
    Unparseable,
    /// Repeating itself — the same n-gram cycling. The classic stuck-decode signature, and free to
    /// detect since the engine already ships n-gram machinery for `lookupdraft`.
    Looping,
    /// A sibling reached a strictly better verified state from the same fork and this branch has
    /// produced nothing distinguishing. Dominance, not failure.
    Dominated,
}

impl KillCause {
    /// Can this cause be wrong about a branch that would have succeeded?
    ///
    /// `Unparseable` and `Budget` are decidable facts about the text so far. `Looping` and
    /// `Dominated` are judgements, and a policy that treats them as facts will quietly discard
    /// branches that were about to break out of a rut or diverge usefully.
    pub fn is_decidable(&self) -> bool {
        matches!(self, KillCause::Unparseable | KillCause::Budget)
    }
}

/// One slot's occupancy.
#[derive(Clone, Copy, Debug)]
pub struct Slot {
    pub id: usize,
    /// Tokens generated by the branch currently in this slot.
    pub pos: usize,
    /// Tokens this branch was allotted.
    pub budget: usize,
    pub occupied: bool,
}

impl Slot {
    pub fn free(id: usize) -> Self { Slot { id, pos: 0, budget: 0, occupied: false } }
    pub fn fraction_spent(&self) -> f32 {
        if self.budget == 0 { 0.0 } else { self.pos as f32 / self.budget as f32 }
    }
}

/// What to do with a branch this step.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Verdict {
    Continue,
    /// Stop generating, free the slot for a fork. Nothing is told anything — the branch simply
    /// stops receiving compute, which is the one signal a model cannot misread.
    Reap(KillCause),
}

/// Kill policy. Deliberately holds no model and reads no text: callers pass in the results of
/// checks they ran, so the policy is testable and the checks are swappable.
#[derive(Clone, Copy, Debug)]
pub struct Reaper {
    /// Reap on judgement-based causes, not just decidable ones. Off is the conservative default:
    /// start by reaping only what is certainly dead, measure the yield, then decide whether the
    /// extra turnover is worth the false-kill risk.
    pub reap_judgements: bool,
    /// Never reap inside the first this-many tokens. A branch that has produced three tokens has not
    /// yet had a chance to be anything, and `Unparseable` fires trivially on partial output.
    pub grace: usize,
    /// Minimum lead a sibling needs before `Dominated` counts. Zero would reap every branch that is
    /// momentarily behind, which is every branch some of the time.
    pub dominance_margin: f32,
}

impl Default for Reaper {
    fn default() -> Self { Reaper { reap_judgements: false, grace: 16, dominance_margin: 0.15 } }
}

/// What the caller observed about a branch this step.
#[derive(Clone, Copy, Debug, Default)]
pub struct Signs {
    pub unparseable: bool,
    pub looping: bool,
    /// Best sibling's score minus this branch's, from the same fork. Negative means it is ahead.
    pub sibling_lead: f32,
}

impl Reaper {
    pub fn judge(&self, slot: &Slot, s: &Signs) -> Verdict {
        if !slot.occupied { return Verdict::Continue; }
        // Budget is checked before grace: a branch past its allotment is over regardless of how
        // recently it started, and grace exists to protect young branches from JUDGEMENTS.
        if slot.budget > 0 && slot.pos >= slot.budget { return Verdict::Reap(KillCause::Budget); }
        if slot.pos < self.grace { return Verdict::Continue; }
        if s.unparseable { return Verdict::Reap(KillCause::Unparseable); }
        if !self.reap_judgements { return Verdict::Continue; }
        if s.looping { return Verdict::Reap(KillCause::Looping); }
        if s.sibling_lead > self.dominance_margin { return Verdict::Reap(KillCause::Dominated); }
        Verdict::Continue
    }
}

/// Hypotheses started per slot per round, given reaping.
///
/// `reaped` is the fraction of branches that get killed early, `at_fraction` the mean point in
/// their budget where it happens. Survivors hold their slot for the whole round.
///
/// The shape worth internalising: yield is bounded by `1/at_fraction` no matter how many branches
/// are reaped, because a slot cannot turn over faster than its occupants die. Reaping 100% of
/// branches at 90% of budget buys 11%.
pub fn slot_yield(reaped: f32, at_fraction: f32) -> f32 {
    let r = reaped.clamp(0.0, 1.0);
    let f = at_fraction.clamp(1e-3, 1.0);
    // Mean slot-time per hypothesis, in rounds: survivors take 1, reaped take `f`.
    let mean_occupancy = r * f + (1.0 - r) * 1.0;
    1.0 / mean_occupancy
}

/// Hypotheses per round for a whole population, and the KV it costs.
///
/// KV is unchanged by reaping — that is the entire point. Slots are reserved up front, so turnover
/// is free capacity rather than more memory.
pub fn population_yield(slots: usize, reaped: f32, at_fraction: f32) -> f32 {
    slots as f32 * slot_yield(reaped, at_fraction)
}

/// Expected solutions lost per round to a detector that condemns good branches.
///
/// The counterweight to `slot_yield`. A reaper that doubles throughput while false-killing 3% of a
/// 32-slot round discards about one viable hypothesis per round, and viable hypotheses are the
/// scarce thing.
pub fn solutions_lost(slots: usize, false_kill_rate: f32, good_fraction: f32) -> f32 {
    slots as f32 * false_kill_rate.clamp(0.0, 1.0) * good_fraction.clamp(0.0, 1.0)
}

/// Is reaping paying for itself? Compares extra hypotheses gained against viable ones destroyed,
/// both per round.
///
/// `success_rate` is the fraction of hypotheses that would have worked out — with a 100:1 failure
/// ratio that is 0.01, and at that rate a lot of false killing is affordable. At a 10:1 ratio it
/// is not.
pub fn worth_it(slots: usize, reaped: f32, at_fraction: f32, false_kill_rate: f32, success_rate: f32) -> (f32, f32) {
    let base = slots as f32;
    let gained = population_yield(slots, reaped, at_fraction) - base;
    // The EXTRA hypotheses a fast detector buys are subject to that same detector, so they are
    // false-killed at the same rate. Omitting this made a detector measured at a 70.8% false-kill
    // rate report that it "pays" at every success rate, because the gain term grew untouched while
    // only the loss term was discounted. A reaper that destroys seven good branches in ten cannot
    // pay, and the arithmetic has to be able to say so.
    let fk = false_kill_rate.clamp(0.0, 1.0);
    let expected_extra_solutions = gained * success_rate * (1.0 - fk);
    let lost = solutions_lost(slots, fk, success_rate);
    (expected_extra_solutions, lost)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn occupied(pos: usize, budget: usize) -> Slot { Slot { id: 0, pos, budget, occupied: true } }

    #[test]
    fn a_free_slot_is_never_reaped() {
        let r = Reaper::default();
        assert_eq!(r.judge(&Slot::free(3), &Signs { unparseable: true, ..Default::default() }), Verdict::Continue);
    }

    #[test]
    fn grace_protects_young_branches_from_syntactic_checks() {
        let r = Reaper::default();
        let signs = Signs { unparseable: true, ..Default::default() };
        assert_eq!(r.judge(&occupied(4, 400), &signs), Verdict::Continue, "4 tokens is not a program");
        assert_eq!(r.judge(&occupied(64, 400), &signs), Verdict::Reap(KillCause::Unparseable));
    }

    #[test]
    fn budget_overrules_grace_because_it_is_not_a_judgement() {
        let r = Reaper { grace: 100, ..Default::default() };
        assert_eq!(r.judge(&occupied(10, 10), &Signs::default()), Verdict::Reap(KillCause::Budget));
    }

    #[test]
    fn judgement_causes_are_off_by_default() {
        let r = Reaper::default();
        let looping = Signs { looping: true, sibling_lead: 0.9, ..Default::default() };
        assert_eq!(r.judge(&occupied(64, 400), &looping), Verdict::Continue);
        let bold = Reaper { reap_judgements: true, ..Default::default() };
        assert_eq!(bold.judge(&occupied(64, 400), &looping), Verdict::Reap(KillCause::Looping));
    }

    #[test]
    fn dominance_needs_a_margin_or_it_reaps_everyone_behind() {
        let r = Reaper { reap_judgements: true, ..Default::default() };
        let barely = Signs { sibling_lead: 0.10, ..Default::default() };
        assert_eq!(r.judge(&occupied(64, 400), &barely), Verdict::Continue);
        let clearly = Signs { sibling_lead: 0.40, ..Default::default() };
        assert_eq!(r.judge(&occupied(64, 400), &clearly), Verdict::Reap(KillCause::Dominated));
    }

    #[test]
    fn only_syntactic_causes_are_decidable() {
        assert!(KillCause::Unparseable.is_decidable());
        assert!(KillCause::Budget.is_decidable());
        assert!(!KillCause::Looping.is_decidable());
        assert!(!KillCause::Dominated.is_decidable());
    }

    #[test]
    fn no_reaping_yields_exactly_one_hypothesis_per_slot() {
        assert!((slot_yield(0.0, 0.2) - 1.0).abs() < 1e-6);
        assert!((population_yield(32, 0.0, 0.2) - 32.0).abs() < 1e-4);
    }

    #[test]
    fn yield_is_capped_by_when_branches_die_not_by_how_many() {
        // Reaping everything at 90% of budget is nearly worthless...
        assert!(slot_yield(1.0, 0.9) < 1.15);
        // ...and reaping everything at 20% is the 5x.
        assert!((slot_yield(1.0, 0.2) - 5.0).abs() < 1e-4);
        // Reaping the realistic 90% of branches at 20% gives most of it.
        let y = slot_yield(0.9, 0.2);
        assert!(y > 3.5 && y < 4.0, "yield {y}");
    }

    #[test]
    fn late_reaping_cannot_be_rescued_by_reaping_more() {
        let all_late = slot_yield(1.0, 0.8);
        let some_early = slot_yield(0.5, 0.1);
        assert!(some_early > all_late, "{some_early} vs {all_late} — WHEN beats HOW MANY");
    }

    #[test]
    fn a_high_failure_ratio_is_what_makes_false_kills_affordable() {
        // 100:1 — the ratio the population design assumes. Reap 90% at 20% of budget, false-kill 3%.
        let (gained, lost) = worth_it(32, 0.9, 0.2, 0.03, 0.01);
        assert!(gained > lost * 8.0, "gained {gained} lost {lost}");
        // 10:1, same reaper: still positive but the margin has collapsed by an order of magnitude.
        let (g2, l2) = worth_it(32, 0.9, 0.2, 0.03, 0.10);
        assert!(g2 > l2);
        assert!(g2 / l2 < gained / lost * 1.01, "the ratio cannot improve as successes get commoner");
    }

    #[test]
    fn a_detector_that_kills_most_good_branches_cannot_pay() {
        // The measured rate of the first, unusable version of corpus.rs: 70.8%.
        let (gained, lost) = worth_it(32, 0.9, 0.2, 0.708, 0.01);
        assert!(gained < lost * 4.0, "gained {gained} lost {lost}");
        // Against the rate after the fixes: 0.8%.
        let (g2, l2) = worth_it(32, 0.9, 0.2, 0.008, 0.01);
        assert!(g2 > l2 * 100.0, "gained {g2} lost {l2}");
    }

    #[test]
    fn a_sloppy_detector_can_lose_more_than_it_gains() {
        // Reaps late and false-kills often: the configuration to catch before shipping it.
        let (gained, lost) = worth_it(32, 0.5, 0.85, 0.20, 0.05);
        assert!(lost > gained, "gained {gained} lost {lost}");
    }
}
