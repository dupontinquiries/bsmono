#!/usr/bin/env python3
"""Export a trained model for vidkit, plus the parity fixture.

  export.py WEIGHTS.json FRAMES.yuv W H FRAME_INDEX

Writes:
- shared/vidkit/crates/vidkit-core/src/aiframes_weights.rs: the CNN's
  weights as Rust constants (layout [out][in][ky][kx], as PyTorch stores
  them), plus the pipeline constants the training used.
- shared/vidkit/crates/vidkit-core/testdata/aiframes_fixture.bin: a
  256x144 crop of a held-out triplet (prev, real middle, next as u8 luma),
  then the model's synthesised luma for it (f32), computed HERE by the
  training code -- so the Rust reference and the GPU shader are checked
  against PyTorch itself, not against each other.
"""
import json
import os
import struct
import sys

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import train as T  # noqa: E402

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../.."))
CORE = os.path.join(REPO, "shared/vidkit/crates/vidkit-core")


def main():
    wpath, ypath, w, h, idx = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
    blob = json.load(open(wpath))
    net = T.Refine()
    with torch.no_grad():
        for cv, l in zip(list(net.body) + [net.head], blob["layers"]):
            cv.weight.copy_(torch.tensor(l["w"]))
            cv.bias.copy_(torch.tensor(l["b"]))

    lines = [
        "// GENERATED by apps/vidkit-player/tools/aiframes/export.py -- do not edit.",
        "// The AI half-rate frame synthesiser's trained refinement CNN.",
        f"pub const LEVELS: [usize; {len(blob['levels'])}] = {blob['levels']};",
        f"pub const LK_ITERS: usize = {blob['lk_iters']};",
        f"pub const LK_WIN: usize = {blob['lk_win']};",
        "/// (in channels, out channels, dilation, weights [out][in][ky][kx], bias).",
        "pub const LAYERS: &[(usize, usize, usize, &[f32], &[f32])] = &[",
    ]
    for cv in list(net.body) + [net.head]:
        wt = cv.weight.detach().numpy().astype(np.float32)
        bs = cv.bias.detach().numpy().astype(np.float32)
        wl = ", ".join(repr(float(x)) for x in wt.ravel())
        bl = ", ".join(repr(float(x)) for x in bs.ravel())
        lines.append(f"    ({wt.shape[1]}, {wt.shape[0]}, {cv.dilation[0]}, &[{wl}], &[{bl}]),")
    lines.append("];")
    with open(os.path.join(CORE, "src/aiframes_weights.rs"), "w") as f:
        f.write("\n".join(lines) + "\n")

    y, _, _ = T.load(ypath, w, h)
    fw, fh = 256, 144
    # The crop with the most motion in this triplet, 16-aligned.
    best = None
    for oy in range(0, h - fh + 1, 16):
        for ox in range(0, w - fw + 1, 16):
            d = np.abs(y[idx + 2, oy:oy + fh:4, ox:ox + fw:4].astype(np.int16) - y[idx, oy:oy + fh:4, ox:ox + fw:4]).mean()
            if best is None or d > best[0]:
                best = (d, oy, ox)
    _, oy, ox = best
    a, b, c = (y[k, oy:oy + fh, ox:ox + fw].copy() for k in (idx, idx + 1, idx + 2))
    with torch.no_grad():
        t0, t2 = T.to_t(a[None]), T.to_t(c[None])
        out = T.model_flow(net, t0, t2)
        (py,) = T.synth(out, [t0], [t2])
    synth = py[0, 0].numpy().astype(np.float32)
    os.makedirs(os.path.join(CORE, "testdata"), exist_ok=True)
    with open(os.path.join(CORE, "testdata/aiframes_fixture.bin"), "wb") as f:
        f.write(struct.pack("<II", fw, fh))
        f.write(a.tobytes() + b.tobytes() + c.tobytes())
        f.write(synth.tobytes())
    bl = T.psnr((t0 + t2) / 2, T.to_t(b[None]))
    print(f"fixture: frame {idx} crop ({ox},{oy}) {fw}x{fh}; model {T.psnr(py, T.to_t(b[None])):.2f} dB vs blend {bl:.2f} dB on it")
    print("wrote", os.path.join(CORE, "src/aiframes_weights.rs"), "and testdata/aiframes_fixture.bin")


if __name__ == "__main__":
    main()
