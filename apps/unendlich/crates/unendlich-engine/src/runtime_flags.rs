//! Runtime flags / environment-variable help (v0.22.0+).
//!
//! Centralizes the list of env vars that affect runtime behaviour
//! across binaries. Provides a `--help` printer that any binary
//! can call early in `main()` and exit cleanly on.
//!
//! # Why a registry, not just `clap`
//!
//! Using `clap` would mean teaching every binary to parse its own
//! flags, which conflicts with the env-var-based knobs that
//! deliberately work for ALL binaries (so the user can run any of
//! them with the same `UNENDLICH_RENDER_DISTANCE` setting). A small
//! shared registry keeps the surface area minimal.
//!
//! # Adding a new flag
//!
//! Add a `Flag` entry to [`flags()`] and update the consumer to
//! read the env var via the helper of its choice. The help text
//! generated by [`print_help`] reflects the registry automatically.
//!
//! # Sample
//!
//! ```text
//! $ unendlich-world --help
//! unendlich engine — runtime flags
//!
//! Recognized command-line flags:
//!   --help, -h          Print this help and exit.
//!   --version, -V       Print version and exit.
//!
//! Environment variables (read at startup):
//!   UNENDLICH_RENDER_DISTANCE=N   ...
//!   ...
//! ```

use std::ops::RangeInclusive;

/// One configurable knob exposed to the user.
pub struct Flag {
    /// Env var name. `None` for non-env CLI-only flags (currently
    /// none — included for symmetry).
    pub env: &'static str,
    /// What the variable controls, in one sentence.
    pub summary: &'static str,
    /// Default value (as user would type it).
    pub default: &'static str,
    /// Valid range or set, e.g. `"0|1"` or `"1..=256"`.
    pub valid: &'static str,
    /// Which binaries respect this knob. `&[]` means "all".
    pub binaries: &'static [&'static str],
}

/// Named flag bundles ("profiles") that codify a blessed set of knobs so a run
/// is one flag instead of two dozen. The bin applies these EARLY (before any
/// `env::var` read) with set-if-unset semantics, so an explicit env var the user
/// passes on the command line always overrides the profile value.
///
/// Returns the `(env, value)` pairs for `name`, or `None` if unknown.
pub fn profile(name: &str) -> Option<&'static [(&'static str, &'static str)]> {
    match name {
        // RD=24 quality preset — the settled perf/quality cluster from R27 tuning:
        // prefetch + GPU octree mesher (near+mid) + device-local meshes + the
        // upload/scheduler toggles + cheap-stride shadows + a tight near LOD band.
        // NOT baked (vary these per run): eye-candy (POSTFX/BLOOM/SEASONS/WEATHER/
        // GPU_DECORATE), OCTREE_POOL_MB, SPAWN_ARCHE.
        "rd24" => Some(&[
            ("UNENDLICH_PREFETCH", "1"),
            ("UNENDLICH_PREFETCH_COUNT", "16"),
            ("UNENDLICH_PREFETCH_LOOKAHEAD", "16"),
            ("UNENDLICH_RENDER_DISTANCE", "24"),
            ("UNENDLICH_LOD_BANDS", "4,10,24"),
            ("UNENDLICH_LOD_FIDELITY", "0.25"),
            ("UNENDLICH_GPU_MESHER", "2"),
            ("UNENDLICH_GPU_MESHER_MID", "2"),
            ("UNENDLICH_GPU_MESH_BATCH", "256"),
            ("UNENDLICH_GPU_GEN_BATCH", "256"),
            ("UNENDLICH_DEVICE_LOCAL_MESH", "1"),
            ("UNENDLICH_MAX_UPLOADS_PER_FRAME", "128"),
            ("UNENDLICH_UPLOAD_BUDGET_MS", "8"),
            ("UNENDLICH_ADAPTIVE_UPLOADS", "1"),
            ("UNENDLICH_SUBMIT_SKIP", "1"),
            ("UNENDLICH_SLACK_SCHEDULER", "1"),
            ("UNENDLICH_BIASED_SHELL_WALK", "1"),
            ("UNENDLICH_UPLOAD_PRIORITY", "1"),
            ("UNENDLICH_REMESH_GATE", "1"),
            ("UNENDLICH_SKY_CULL", "1"),
            ("UNENDLICH_SHADOW_CACHE", "1"),
            ("UNENDLICH_SHADOW_CHUNK_STRIDE", "2"),
            ("UNENDLICH_SHADOW_MAP_SIZE", "512"),
            ("UNENDLICH_APPLY_BUDGET", "32"),
            ("UNENDLICH_EVICT_BUDGET", "32"),
        ]),
        _ => None,
    }
}

/// All known profile names (for help text + tests).
pub fn profile_names() -> &'static [&'static str] {
    &["rd24"]
}

