/// Returns true if argv contains `--help` or `-h`.
pub fn wants_help() -> bool {
    std::env::args().skip(1).any(|a| a == "--help" || a == "-h")
}

/// Returns true if argv contains `--version` or `-V`.
pub fn wants_version() -> bool {
    std::env::args().skip(1).any(|a| a == "--version" || a == "-V")
}

/// Print help text to stdout. The current binary's name is used to
/// filter the listed env vars so the user sees only the ones that
/// actually affect them — but vars that apply globally
/// (`binaries == &[]`) are always shown.
pub fn print_help(binary_name: &str) {
    let version = env!("CARGO_PKG_VERSION");
    println!("unendlich engine v{version} — runtime flags ({binary_name})\n");
    println!("Recognized command-line flags:");
    println!("  --help, -h          Print this help and exit.");
    println!("  --version, -V       Print version and exit.");
    println!();
    println!("Environment variables (read at startup):");

    let max_env_len = flags()
        .iter()
        .filter(|f| f.binaries.is_empty() || f.binaries.contains(&binary_name))
        .map(|f| f.env.len())
        .max()
        .unwrap_or(0);

    for f in flags() {
        let applies = f.binaries.is_empty() || f.binaries.contains(&binary_name);
        if !applies { continue; }

        let scope = if f.binaries.is_empty() {
            "(all)".to_string()
        } else {
            format!("({})", f.binaries.join(", "))
        };

        // Wrap summary at ~60 chars after the indent.
        let indent = " ".repeat(max_env_len + 6);
        let summary = wrap_to_width(f.summary, 64, &indent);

        println!(
            "  {env:<width$}  {summary}",
            env = f.env, width = max_env_len, summary = summary,
        );
        println!("{indent}default: {}   valid: {}   scope: {}",
                 f.default, f.valid, scope);
        println!();
    }

    println!("Examples:");
    println!("  UNENDLICH_RENDER_DISTANCE=12 cargo run --release \\");
    println!("    --features render --features gpu --bin unendlich-world");
    println!("  UNENDLICH_INDIRECT=0 ./{}    # diagnose indirect-draw regression", binary_name);
    println!();
    println!("Project docs: docs/DESIGN_NOTES.md, docs/SHADER_ROADMAP.md");
}

/// Print just the version line.
pub fn print_version(binary_name: &str) {
    println!("{} {}", binary_name, env!("CARGO_PKG_VERSION"));
}

/// Build a multi-line string summarizing the *currently effective*
/// flag values for `binary_name`. For each registered flag whose
/// scope includes this binary (or is global), reports either the
/// env-var value the user actually set, or the registry default
/// (annotated as such).
///
/// Intended for the shutdown summary block — when a user reports a
/// crash, having `RD=32 LOD_FACTORS=4,8,16,32 INDIRECT=1 VSYNC=1`
/// in the log makes the difference between a guessable repro and
/// a guess. Cheap to compute (one `env::var` per flag, ~6 flags).
///
/// Format:
/// ```text
/// Flags in effect (binary=unendlich-world):
///   UNENDLICH_RENDER_DISTANCE = 32
///   UNENDLICH_LOD_FACTORS     = 4,8,16,32
///   UNENDLICH_VSYNC           = 1
///   UNENDLICH_INDIRECT        = 1
///   RUST_LOG                  = (default)
/// ```
///
/// We don't try to *interpret* the value (no clamping, no parse
/// rewrite). The point is to record what the user typed, not what
/// the binary derived from it. The latter is logged by individual
/// subsystems already (e.g. `LodSettings: factors per tier =
/// [4,8,16,32]`).
pub fn flags_summary(binary_name: &str) -> String {
    use std::fmt::Write as _;

    let mut out = String::new();
    let _ = writeln!(out, "Flags in effect (binary={}):", binary_name);

    let max_env_len = flags()
        .iter()
        .filter(|f| f.binaries.is_empty() || f.binaries.contains(&binary_name))
        .map(|f| f.env.len())
        .max()
        .unwrap_or(0);

    for f in flags() {
        let applies = f.binaries.is_empty() || f.binaries.contains(&binary_name);
        if !applies { continue; }

        let value = match std::env::var(f.env) {
            Ok(v) => v,
            Err(_) => format!("(default: {})", f.default),
        };

        let _ = writeln!(out, "  {env:<width$} = {val}",
                         env = f.env, width = max_env_len, val = value);
    }

    // Trim the trailing newline so the caller's `log::info!` doesn't
    // double-space.
    while out.ends_with('\n') { out.pop(); }
    out
}

/// Emit one structured `flag` event per applicable flag for this
/// binary. Each event records env name, current effective value, and
/// whether the value came from the environment or the registry default.
///
/// Called once at startup by the binary. Output goes through
/// `unendlich_shared::events::record(…)` which is a no-op if no event sink
/// has been initialised — keeping this function safe to call from
/// tests that haven't set one up.
///
/// The events parallel `flags_summary` but in machine-parseable form,
/// so `unendlich-analyze` can filter runs by flag value without
/// scraping prose.
pub fn emit_flag_events(binary_name: &str) {
    for f in flags() {
        let applies = f.binaries.is_empty() || f.binaries.contains(&binary_name);
        if !applies { continue; }

        let (value, source) = match std::env::var(f.env) {
            Ok(v) => (v, "env"),
            Err(_) => (f.default.to_string(), "default"),
        };

        unendlich_shared::events::record("flag", serde_json::json!({
            "name": f.env,
            "value": value,
            "source": source,
        }));
    }
}

/// Wrap a long summary string to a max width per line, indenting
/// continuation lines. Naive; word-by-word.
fn wrap_to_width(s: &str, width: usize, indent: &str) -> String {
    let mut out = String::new();
    let mut col = 0usize;
    for word in s.split_whitespace() {
        let needed = if col == 0 { word.len() } else { word.len() + 1 };
        if col + needed > width {
            out.push('\n');
            out.push_str(indent);
            out.push_str(word);
            col = word.len();
        } else {
            if col != 0 { out.push(' '); col += 1; }
            out.push_str(word);
            col += word.len();
        }
    }
    out
}

/// Helper: read an env var as a clamped i32 with a default.
pub fn env_i32(name: &str, default: i32, range: RangeInclusive<i32>) -> i32 {
    match std::env::var(name) {
        Ok(v) => match v.parse::<i32>() {
            Ok(n) if range.contains(&n) => n,
            Ok(n) => {
                log::warn!("{}={} out of {:?}; using {}", name, n, range, default);
                default
            }
            Err(_) => {
                log::warn!("{}={} not a valid i32; using {}", name, v, default);
                default
            }
        },
        Err(_) => default,
    }
}

/// Helper: read an env var as a usize clamped to [1, max].
pub fn env_usize(name: &str, default: usize, max: usize) -> usize {
    match std::env::var(name) {
        Ok(v) => match v.parse::<usize>() {
            Ok(n) if (1..=max).contains(&n) => n,
            Ok(n) => {
                log::warn!("{}={} out of [1,{}]; using {}", name, n, max, default);
                default
            }
            Err(_) => {
                log::warn!("{}={} not a valid usize; using {}", name, v, default);
                default
            }
        },
        Err(_) => default,
    }
}

