    #[test]
    fn dtw_bounded_equals_unbounded_when_cutoff_not_binding() {
        // If the bounded path ever diverged from the unbounded one
        // under a non-binding cutoff, matching would silently change
        // depending on which code path ran. Pin that they agree.
        let a = seq(10, 1.0);
        let b = seq(8, 2.0);
        let unb = dtw_distance(&a, 10, &b, 8);
        assert!((unb - dtw_distance_bounded(&a, 10, &b, 8, f32::INFINITY)).abs() < 1e-4);
        assert!((unb - dtw_distance_bounded(&a, 10, &b, 8, 1e9)).abs() < 1e-4);
    }

