    #[test]
    fn frame_distance_skips_energy_coef() {
        // coef 0 (energy) is intentionally ignored; differing only in
        // coef 0 should give distance 0.
        let mut a = vec![0.0f32; N_MFCC];
        let mut b = vec![0.0f32; N_MFCC];
        a[0] = 100.0; b[0] = -100.0; // huge energy diff, should NOT count
        assert!(frame_distance(&a, &b).abs() < 1e-6);
        // differing in coef 1 SHOULD count
        b[1] = 3.0;
        assert!((frame_distance(&a, &b) - 3.0).abs() < 1e-4);
    }

    #[test]
    fn mel_to_hz_monotonic_and_zero_anchored() {
        // mel 0 → 0 Hz; strictly increasing.
        assert!(mel_to_hz(0.0).abs() < 1e-3);
        let mut last = -1.0;
        for m in 0..30 {
            let hz = mel_to_hz(m as f32 * 100.0);
            assert!(hz > last, "mel_to_hz must be monotonic");
            last = hz;
        }
    }

    // v0.1.496: speaker-merge fix — the sharpened similarity must keep
    // the same person matched while pushing clearly-different speakers
    // below the 0.65 identify threshold.
    fn tp(pitch: f32, activity: f32) -> TonalProfile {
        let mut p = TonalProfile::default();
        p.pitch_hz = pitch;
        p.activity = activity;
        p
    }

    #[test]
    fn similarity_keeps_same_person_matched() {
        // a few-percent day-to-day pitch drift must stay well above
        // the 0.65 identify threshold.
        let s = tp(110.0, 0.60).similarity(&tp(113.0, 0.62));
        assert!(s >= 0.65, "same person must still match: {}", s);
    }

    #[test]
    fn similarity_separates_clearly_different_speakers() {
        // two different males ~12% apart in pitch must NOT merge.
        let s = tp(110.0, 0.60).similarity(&tp(125.0, 0.65));
        assert!(s < 0.65, "different males must not merge: {}", s);
        // and same-person should always out-score this different-person pair.
        let same = tp(110.0, 0.60).similarity(&tp(113.0, 0.62));
        assert!(same > s, "same-person must out-score different-person");
    }

    #[test]
    fn similarity_zero_pitch_is_neutral() {
        // missing pitch → neutral 0.5 (below identify threshold, so we
        // don't merge on no information).
        assert_eq!(tp(0.0, 0.5).similarity(&tp(110.0, 0.5)), 0.5);
        assert!(0.5 < 0.65, "neutral score must be below identify threshold");
    }

    #[test]
    fn similarity_survives_nonfinite_and_wild_profiles() {
        // v0.1.588: a corrupt/old on-disk fingerprint could carry
        // NaN/inf pitch or out-of-range activity. similarity() must
        // never return NaN (it would poison the whole speaker match) and
        // must stay in [0,1]. NaN/inf → neutral 0.5; wild activity is
        // clamped, not propagated.
        for (a, b) in [
            (tp(f32::NAN, 0.5), tp(200.0, 0.5)),
            (tp(f32::INFINITY, 0.5), tp(200.0, 0.5)),
            (tp(200.0, f32::NAN), tp(200.0, 0.5)),
            (tp(200.0, 5.0), tp(200.0, -3.0)),
        ] {
            let s = a.similarity(&b);
            assert!(s.is_finite(), "similarity must be finite, got {s}");
            assert!((0.0..=1.0).contains(&s), "similarity must be in [0,1], got {s}");
        }
        // non-finite cases specifically resolve to the neutral 0.5
        assert_eq!(tp(f32::NAN, 0.5).similarity(&tp(200.0, 0.5)), 0.5);
    }

    #[test]
    fn from_audio_survives_pathological_input() {
        // v0.1.558: a non-empty buffer of NaN/inf samples (audio-driver
        // glitch, denormals, capture corruption) must NOT yield a NaN
        // TonalProfile — that poisons all downstream speaker-match math.
        // The empty-guard alone did not cover this; from_audio now
        // filters non-finite samples + clamps rms.
        let cases: Vec<(&str, Vec<f32>)> = vec![
            ("all-nan", vec![f32::NAN; 4096]),
            ("all-inf", vec![f32::INFINITY; 4096]),
            ("neg-inf", vec![f32::NEG_INFINITY; 4096]),
            ("mixed-nan", (0..4096).map(|i| if i % 7 == 0 { f32::NAN } else { 0.3 }).collect()),
            ("huge", vec![1e30; 4096]),
            ("zeros", vec![0.0; 4096]),
        ];
        for (label, audio) in cases {
            let p = TonalProfile::from_audio(&audio);
            assert!(p.pitch_hz.is_finite(), "{label}: pitch_hz not finite");
            assert!(p.rms.is_finite(), "{label}: rms not finite");
            assert!(p.activity.is_finite(), "{label}: activity not finite");
            assert!(p.spectral_centroid_hz.is_finite(), "{label}: centroid not finite");
            assert!(p.voicing_prob.is_finite(), "{label}: voicing not finite");
            // and the profile must produce a finite similarity score
            let s = p.similarity(&TonalProfile::from_audio(&vec![0.2f32; 4096]));
            assert!(s.is_finite() && (0.0..=1.0).contains(&s),
                "{label}: similarity out of range: {s}");
        }
    }
