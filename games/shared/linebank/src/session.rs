//! SESSION — bytes in, labelled takes out.
//!
//! Five pieces now exist across three crates: `audio-kit`'s WAV parser and
//! millisecond envelope, this crate's [`slice`](crate::slice) segmenter,
//! [`assign`](crate::slice::assign), [`verify`](crate::verify), and
//! [`assets`](crate::assets)'s budget. Each is tested. **Nothing had shown
//! they fit together**, which is the same gap as a trait with no
//! implementors — a pipeline that only exists as a diagram in a doc comment
//! is a pipeline nobody has run.
//!
//! [`import`] is the whole path as one call, and
//! `a_synthetic_session_survives_the_entire_pipeline` runs it end to end from
//! generated bytes.
//!
//! ## Why the composition is worth owning rather than leaving to the caller
//!
//! Two of the joins are easy to get wrong and neither is obvious from the
//! individual signatures.
//!
//! * `Wav::samples` is INTERLEAVED, and the segmenter wants one channel. A
//!   caller who passes the interleaved buffer straight through gets an
//!   envelope with both channels smeared into it, and on a stereo take that is
//!   quietly a different signal rather than an error.
//! * The sample rate travels separately from the samples all the way down —
//!   `Segmenter::segment`, `Span::seconds`, and the budget each need it, and
//!   nothing in the type system objects if a caller hands one of them the
//!   wrong one.
//!
//! Holding both in one function means they can only be got wrong once.

use crate::assets::{budget, Budget, Quality};
use crate::slice::{assign, Assigned, Expected, Mismatch, Segmenter, Span};
use crate::verify::{blocking, Finding};

/// Everything an import produced.
#[derive(Clone, Debug)]
pub struct Import {
    /// Every span of sound found, including the slates.
    pub spans: Vec<Span>,
    /// Spans matched to units, slates dropped.
    pub takes: Vec<Assigned>,
    /// Fingerprint audit, empty when no similarity function was supplied.
    pub findings: Vec<Finding>,
    /// What these takes will cost once encoded.
    pub budget: Budget,
    pub sample_rate: u32,
    pub channels: u16,
}

impl Import {
    /// Findings serious enough to stop on.
    pub fn blockers(&self) -> Vec<&Finding> {
        blocking(&self.findings)
    }
    pub fn seconds(&self) -> f32 {
        self.takes.iter().map(|t| t.span.seconds(self.sample_rate)).sum()
    }
}

/// Why an import failed outright, as opposed to producing findings.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum ImportError {
    /// The file did not parse.
    Audio(crate::wav_error::WavError),
    /// The span count did not match the script. See
    /// [`Mismatch`](crate::slice::Mismatch) — the numbers are the diagnosis.
    Alignment(Mismatch),
    /// Parsed, but nothing above the noise floor. An unplugged microphone
    /// looks exactly like this, which is why it is its own error rather than
    /// an empty success.
    NoAudio,
}

/// Bytes of a recorded session to labelled takes.
///
/// `expected` is the script order. `slated` means the actor announced each id
/// before reading it, which is what `Bank::script_for` instructs.
pub fn import(
    wav_bytes: &[u8],
    expected: &[Expected],
    slated: bool,
    seg: Segmenter,
) -> Result<Import, ImportError> {
    let w = audio_kit::wav::parse(wav_bytes)
        .map_err(|e| ImportError::Audio(crate::wav_error::WavError::from(e)))?;

    // Interleaved in, one channel out. A stereo take smeared into a single
    // envelope is not an error anywhere downstream, just a different signal.
    let mono = w.mono();
    let spans = seg.segment(&mono, w.sample_rate);
    if spans.is_empty() {
        return Err(ImportError::NoAudio);
    }

    let takes = assign(&spans, expected, slated).map_err(ImportError::Alignment)?;

    let sized: Vec<(f32, Quality)> = takes
        .iter()
        .zip(expected)
        .map(|(a, e)| (a.span.seconds(w.sample_rate), Quality::for_kind(e.kind)))
        .collect();

    Ok(Import {
        spans,
        takes,
        findings: Vec::new(),
        budget: budget(&sized),
        sample_rate: w.sample_rate,
        channels: w.channels,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::verify::audit;
    use crate::Kind;

    const SR: u32 = 48_000;

    fn tone(secs: f32, amp: f32, sr: u32) -> Vec<f32> {
        let n = (secs * sr as f32) as usize;
        (0..n).map(|i| amp * (i as f32 * 0.05).sin()).collect()
    }
    fn room(secs: f32, sr: u32) -> Vec<f32> {
        let n = (secs * sr as f32) as usize;
        (0..n).map(|i| 0.0008 * (i as f32 * 0.31).sin()).collect()
    }

    /// A session shaped the way the script asks: slate, read, beat.
    fn session(sr: u32, reads: &[f32]) -> Vec<f32> {
        let mut v = room(0.5, sr);
        for r in reads {
            v.extend(tone(0.30, 0.5, sr)); // the slate
            v.extend(room(0.5, sr));
            v.extend(tone(*r, 0.6, sr)); // the read
            v.extend(room(0.5, sr));
        }
        v
    }

    fn expected(items: &[(&str, u8, Kind)]) -> Vec<Expected> {
        items
            .iter()
            .map(|(u, n, k)| Expected { unit: u.to_string(), n: *n, kind: *k })
            .collect()
    }

    #[test]
    fn a_synthetic_session_survives_the_entire_pipeline() {
        // audio-kit writes the bytes, audio-kit parses them, audio-kit's
        // envelope drives the segmenter, assign labels them, assets prices
        // them. If any seam is wrong this is where it shows.
        let samples = session(SR, &[0.4, 0.35, 1.8]);
        let bytes = audio_kit::wav::write_f32(&samples, SR, 1);

        let e = expected(&[
            ("billy_ack", 1, Kind::Blip),
            ("billy_ack", 2, Kind::Blip),
            ("billy_one_shot", 1, Kind::Phrase),
        ]);
        let imp = import(&bytes, &e, true, Segmenter::default()).expect("import failed");

        assert_eq!(imp.spans.len(), 6, "slates and reads: {:?}", imp.spans);
        assert_eq!(imp.takes.len(), 3);
        assert_eq!(imp.sample_rate, SR);
        assert_eq!(imp.takes[2].unit, "billy_one_shot");

        // the reads, not the slates: the long one must be the phrase
        let d = imp.takes[2].span.seconds(SR);
        assert!(d > 1.5 && d < 2.1, "the phrase came back as {d:.2}s");

        // and the budget priced the blips cheaper than the phrase
        assert!(imp.budget.per_file > 0);
        assert!(imp.seconds() > 2.0);
    }

    #[test]
    fn the_same_session_at_44100_imports_identically() {
        // The payoff of moving detection onto the millisecond envelope,
        // asserted at the level a tool actually uses.
        let e = expected(&[("a", 1, Kind::Blip), ("b", 1, Kind::Blip)]);
        let mut got = Vec::new();
        for sr in [48_000u32, 44_100] {
            let bytes = audio_kit::wav::write_f32(&session(sr, &[0.4, 0.5]), sr, 1);
            let imp = import(&bytes, &e, true, Segmenter::default()).expect("import failed");
            got.push(imp);
        }
        assert_eq!(got[0].takes.len(), got[1].takes.len());
        for (a, b) in got[0].takes.iter().zip(&got[1].takes) {
            let (x, y) = (a.span.seconds(48_000), b.span.seconds(44_100));
            assert!((x - y).abs() < 0.02, "{x:.3}s vs {y:.3}s");
        }
    }

    #[test]
    fn a_stereo_take_is_folded_rather_than_smeared() {
        // The join a caller gets wrong: Wav::samples is INTERLEAVED. Passing
        // it straight to the segmenter is not an error anywhere, it is just a
        // different signal — so the composition has to do the fold.
        let mono = session(SR, &[0.4]);
        let mut stereo = Vec::with_capacity(mono.len() * 2);
        for s in &mono {
            stereo.push(*s);
            stereo.push(*s);
        }
        let bytes = audio_kit::wav::write_f32(&stereo, SR, 2);
        let e = expected(&[("a", 1, Kind::Blip)]);
        let imp = import(&bytes, &e, true, Segmenter::default()).expect("stereo import failed");
        assert_eq!(imp.channels, 2);
        // durations must match the mono session, not be halved by interleaving
        let d = imp.takes[0].span.seconds(SR);
        assert!(d > 0.35 && d < 0.55, "stereo take measured {d:.3}s");
    }

    #[test]
    fn an_unplugged_microphone_is_its_own_error() {
        // Room tone and nothing else. An empty success here would be imported
        // as "a session with no takes" and the engineer would go looking at
        // the script.
        let bytes = audio_kit::wav::write_f32(&room(4.0, SR), SR, 1);
        let e = expected(&[("a", 1, Kind::Blip)]);
        assert!(matches!(
            import(&bytes, &e, true, Segmenter::default()),
            Err(ImportError::NoAudio)
        ));
    }

    #[test]
    fn a_dropped_slate_refuses_with_the_numbers() {
        let samples = session(SR, &[0.4, 0.4]);
        let bytes = audio_kit::wav::write_f32(&samples, SR, 1);
        // the script says three units; the recording has two
        let e = expected(&[("a", 1, Kind::Blip), ("b", 1, Kind::Blip), ("c", 1, Kind::Blip)]);
        match import(&bytes, &e, true, Segmenter::default()) {
            Err(ImportError::Alignment(Mismatch::Count { found, expected })) => {
                assert_eq!((found, expected), (4, 6));
            }
            other => panic!("expected an alignment refusal, got {other:?}"),
        }
    }

    #[test]
    fn a_corrupt_file_fails_before_anything_else_runs() {
        let e = expected(&[("a", 1, Kind::Blip)]);
        assert!(matches!(
            import(b"not a wav", &e, true, Segmenter::default()),
            Err(ImportError::Audio(_))
        ));
    }

    #[test]
    fn the_audit_composes_onto_a_successful_import() {
        // verify takes a similarity function rather than audio, so it layers
        // on afterwards. Shown here because "how do these two connect" is the
        // question the separate modules do not answer.
        let bytes = audio_kit::wav::write_f32(&session(SR, &[0.4, 0.4]), SR, 1);
        let e = expected(&[("a", 1, Kind::Blip), ("b", 1, Kind::Blip)]);
        let mut imp = import(&bytes, &e, true, Segmenter::default()).unwrap();
        let units = vec!["a".to_string(), "b".to_string()];
        // pretend the two reads were swapped
        imp.findings = audit(&imp.takes, &units, |u, i| match (u, i) {
            ("b", 0) | ("a", 1) => 0.05,
            _ => 0.9,
        });
        assert_eq!(imp.blockers().len(), 2, "{:?}", imp.findings);
    }
}
