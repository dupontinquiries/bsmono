//! partdata — part layouts mined from a vehicle library.
//!
//! The library ships no geometry: it is a catalogue of 5,873 part
//! signatures and, for 178 vehicles, WHERE each part sits. That is a
//! compositional grammar rather than a mesh, and it turns out to be the more
//! interesting input — instead of importing someone's car, a car can be
//! ASSEMBLED from the layout of a tank, a mech or a spaceship.
//!
//! Each donor below is its own point cloud, so each arrives in its own units
//! and axis convention. They are normalised the same way: keep the largest
//! parts (the structure, not the greeble dust), centre the cloud, then map
//! its longest extent to Z, the next to X and the shortest to Y — which puts
//! any donor, however it was authored, onto a car's envelope.
//!
//! Tuple is (class, x, y, z, size) with class:
//!   0 block  1 panel  2 strut  3 disc  4 wheel  5 barrel  6 greeble  7 tread

