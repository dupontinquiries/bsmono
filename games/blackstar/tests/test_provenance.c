/* test_provenance -- the archaeology ladder, C side.

   The inference is implemented twice: once in Rust
   (games/blackstar-rs/src/provenance.rs) and once in provenance.c, because
   the Rust fork drives the sim and the C game draws the CODEX. Duplicated
   logic drifts unless something holds it still, so every fixture below is
   one the Rust test suite also asserts, named after its Rust counterpart.
   If these two ever disagree, this file fails rather than the codex quietly
   showing a different answer than the sim.

   The DATA is not duplicated: archive_gen.h is generated by
   `skydribble --arch emit-c`. */
#include "../engine_src/exengine/provenance.h"
#include "../engine_src/exengine/archive_gen.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>

static const ex_claim_t* claim_of(const char *id) {
  for (int i = 0; i < EX_GEN_CLAIM_COUNT; i++) {
    if (strcmp(ex_gen_claims[i].id, id) == 0) return &ex_gen_claims[i];
  }
  return NULL;
}

static ex_standing_t standing_of(const char *claim_id,
                                 const char *const *found, int n,
                                 float anchor) {
  const ex_received_t *priors[EX_GEN_RECEIVED_COUNT];
  int np = ex_priors_at(ex_gen_received, EX_GEN_RECEIVED_COUNT, anchor,
                        priors, EX_GEN_RECEIVED_COUNT);
  /* ex_assay_claim wants a flat array; rebuild one at the chosen anchor */
  ex_received_t flat[EX_GEN_RECEIVED_COUNT];
  for (int i = 0; i < np; i++) flat[i] = *priors[i];

  const ex_claim_t *c = claim_of(claim_id);
  assert(c && "unknown claim id");
  ex_assay_t a;
  ex_assay_claim(c, ex_gen_findings, EX_GEN_FINDING_COUNT, found, n,
                 flat, np, &a);
  return ex_standing_of(&a);
}

/* --- the ladder itself, independent of content ------------------------- */
static void test_ladder(void) {
  ex_assay_t a;

  memset(&a, 0, sizeof a);
  assert(ex_standing_of(&a) == EX_STANDING_DARK);

  memset(&a, 0, sizeof a); a.mentions = 1;
  assert(ex_standing_of(&a) == EX_STANDING_UNKNOWN);

  memset(&a, 0, sizeof a); a.support = 1;
  assert(ex_standing_of(&a) == EX_STANDING_UNKNOWN);
  a.support = 2; assert(ex_standing_of(&a) == EX_STANDING_POSSIBLE);
  a.support = 3; assert(ex_standing_of(&a) == EX_STANDING_HIGH);
  a.support = 9; assert(ex_standing_of(&a) == EX_STANDING_HIGH);

  /* disagreement is a dispute, not an average */
  memset(&a, 0, sizeof a); a.support = 5; a.opposition = 1;
  assert(ex_standing_of(&a) == EX_STANDING_CONTESTED);

  /* an unasserted claim contradicted alone still draws */
  memset(&a, 0, sizeof a); a.opposition = 1;
  assert(ex_standing_of(&a) == EX_STANDING_CONTESTED);

  /* ... but an ASSERTED one stays dark: you cannot refute an unmade claim */
  memset(&a, 0, sizeof a); a.opposition = 3; a.needs_claimant = 1;
  assert(ex_standing_of(&a) == EX_STANDING_DARK);

  assert(!ex_standing_drawn(EX_STANDING_DARK));
  assert(ex_standing_drawn(EX_STANDING_CONTESTED));
  printf("  ladder ok\n");
}

/* mirrors provenance.rs::one_source_twice_is_still_one_source, using the
   real table: the three Array readings share source "array_logs" */
static void test_one_instrument_is_one_source(void) {
  const char *logs[] = { "array_reading_one", "array_reading_two", "array_reading_three" };
  const ex_claim_t *c = claim_of("edge_lattice");
  ex_assay_t a;
  ex_assay_claim(c, ex_gen_findings, EX_GEN_FINDING_COUNT, logs, 3, NULL, 0, &a);
  assert(a.support == 1 && "three readings off one array counted as three");
  assert(ex_standing_of(&a) == EX_STANDING_UNKNOWN);

  const char *with_wreck[] = { "array_reading_one", "array_reading_two",
                               "array_reading_three", "carrion_hull_scar" };
  ex_assay_claim(c, ex_gen_findings, EX_GEN_FINDING_COUNT, with_wreck, 4, NULL, 0, &a);
  assert(a.support == 2);
  assert(ex_standing_of(&a) == EX_STANDING_POSSIBLE);
  printf("  blackstar's array cannot corroborate itself: ok\n");
}

/* mirrors archive.rs::the_official_history_ends_up_contested */
static void test_official_history_contested(void) {
  const char *found[EX_GEN_FINDING_COUNT];
  for (int i = 0; i < EX_GEN_FINDING_COUNT; i++) found[i] = ex_gen_findings[i].id;

  const ex_claim_t *c = claim_of("facility_built_2003");
  assert(c->asserted && "the official record must be an asserted claim");
  ex_assay_t a;
  ex_assay_claim(c, ex_gen_findings, EX_GEN_FINDING_COUNT, found,
                 EX_GEN_FINDING_COUNT, NULL, 0, &a);
  assert(a.support == 1 && "only the Directorate's own file should support it");
  assert(a.opposition == 3 && "1998, 1996 and 1994 should each be independent");
  assert(ex_standing_of(&a) == EX_STANDING_CONTESTED);
  printf("  official history contested (1 for / 3 against): ok\n");
}

/* mirrors archive.rs::a_high_anchor_hands_you_a_lie_to_catch */
static void test_anchor(void) {
  assert(strcmp(ex_anchor_name(0.0f), "FRESH") == 0);
  assert(strcmp(ex_anchor_name(0.45f), "SPARSE") == 0);
  assert(strcmp(ex_anchor_name(0.62f), "FAMILIAR") == 0);
  assert(strcmp(ex_anchor_name(1.0f), "HOMEY") == 0);

  assert(ex_priors_at(ex_gen_received, EX_GEN_RECEIVED_COUNT, 0.0f, NULL, 0) == 0);
  assert(ex_priors_at(ex_gen_received, EX_GEN_RECEIVED_COUNT, 1.0f, NULL, 0)
         == EX_GEN_RECEIVED_COUNT);

  /* monotone: raising the anchor never removes an assumption */
  int prev = 0;
  for (int s = 0; s <= 20; s++) {
    int n = ex_priors_at(ex_gen_received, EX_GEN_RECEIVED_COUNT,
                         (float)s / 20.0f, NULL, 0);
    assert(n >= prev);
    prev = n;
  }

  /* HOMEY preloads the record; the file adds nothing (same source);
     one dig date starts the fight */
  const char *none[1] = { NULL };
  assert(standing_of("facility_built_2003", none, 0, 1.0f) == EX_STANDING_UNKNOWN);

  const char *file[] = { "directorate_record" };
  const ex_claim_t *c = claim_of("facility_built_2003");
  ex_received_t flat[EX_GEN_RECEIVED_COUNT];
  const ex_received_t *pp[EX_GEN_RECEIVED_COUNT];
  int np = ex_priors_at(ex_gen_received, EX_GEN_RECEIVED_COUNT, 1.0f, pp,
                        EX_GEN_RECEIVED_COUNT);
  for (int i = 0; i < np; i++) flat[i] = *pp[i];
  ex_assay_t a;
  ex_assay_claim(c, ex_gen_findings, EX_GEN_FINDING_COUNT, file, 1, flat, np, &a);
  assert(a.support == 1 && "belief and its own file are one source");

  const char *dig[] = { "trench_excavation_scar" };
  assert(standing_of("facility_built_2003", dig, 1, 1.0f) == EX_STANDING_CONTESTED);

  /* at FRESH the same dig date refutes nothing, because nobody has claimed it */
  assert(standing_of("facility_built_2003", dig, 1, 0.0f) == EX_STANDING_DARK);
  printf("  mystery anchor: ok (FRESH refutes nothing, HOMEY hands you a lie)\n");
}

/* the generated table must stay sane on its own terms */
static void test_generated_tables(void) {
  assert(EX_GEN_CLAIM_COUNT > 0 && EX_GEN_FINDING_COUNT > 0);
  for (int i = 0; i < EX_GEN_FINDING_COUNT; i++) {
    const ex_finding_t *f = &ex_gen_findings[i];
    assert(f->id && f->site && f->source);
    assert(f->link_count > 0 && "a finding that links to nothing is a dead end");
    assert(f->link_count <= 8 && "suspiciously many links; check the emitter");
    for (int k = 0; k < f->link_count; k++) {
      assert(claim_of(f->links[k].claim) && "finding links to an unknown claim");
    }
  }
  for (int i = 0; i < EX_GEN_RECEIVED_COUNT; i++) {
    assert(claim_of(ex_gen_received[i].claim));
    assert(ex_gen_received[i].at >= 0.0f && ex_gen_received[i].at <= 1.0f);
  }
  /* every claim must be reachable by evidence, or it is a dead node */
  for (int i = 0; i < EX_GEN_CLAIM_COUNT; i++) {
    int seen = 0;
    for (int j = 0; j < EX_GEN_FINDING_COUNT && !seen; j++) {
      for (int k = 0; k < ex_gen_findings[j].link_count; k++) {
        if (strcmp(ex_gen_findings[j].links[k].claim, ex_gen_claims[i].id) == 0) { seen = 1; break; }
      }
    }
    assert(seen && "claim unreachable by any finding");
  }
  printf("  generated tables: %d claims, %d findings, %d received -- consistent\n",
         EX_GEN_CLAIM_COUNT, EX_GEN_FINDING_COUNT, EX_GEN_RECEIVED_COUNT);
}

int main(void) {
  printf("test_provenance\n");
  test_ladder();
  test_one_instrument_is_one_source();
  test_official_history_contested();
  test_anchor();
  test_generated_tables();
  printf("provenance: all ok\n");
  return 0;
}
