"""gen_race.py -- author an opening RACE + mid-course PARKOUR run with the openworld library.

A calm, enemy-free traversal course through a beautiful landscape: goal-setting drops
checkpoint POIs, the patrol tour flows them into a racing line, and the height substrate
decides which checkpoints sit up high as PARKOUR gates (you jump/climb/dash to them). No
combat -- this is the quiet, scenic counterpoint to the raid. Bakes race_plan.h.

Run: python3 tools/gen_race.py
"""
import os, sys, json, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from openworld import World, REGISTRY, place_goals, patrol_tour

MAP = "beach"          # a calm shoreline; swap for any serene map
PALETTE = "verdant"    # open, low-cover, scenic
SEED = 4242
SIZE = 90.0
N_CP = 12


def design():
    pal = REGISTRY.get(PALETTE)
    w = World(size=SIZE, seed=SEED, open_sky=True, palette=PALETTE)
    # scenic run: almost no cover, so it reads as open landscape not an arena
    place_goals(w, pal, n=N_CP, seed=SEED, min_spacing=SIZE * 0.20)
    tour = patrol_tour(w, start_xy=(0.0, -SIZE * 0.85))

    course = []
    for i, p in enumerate(tour):
        h = w.height_at(p.x, p.y)                     # 0..1 substrate height at the gate
        # gates on the high ground become PARKOUR (elevated); every 3rd high point too
        parkour = h > 0.62 or (i % 4 == 2 and h > 0.5)
        y = 0.0
        if parkour:
            y = 4.0 + (h - 0.5) * 14.0                # lift onto a platform 4..~11 up
        course.append({"x": round(p.x, 1), "z": round(p.y, 1), "y": round(y, 1),
                       "parkour": 1 if parkour else 0})
    # ensure a clean flat start + a climactic parkour finish
    course[0].update({"x": 0.0, "z": -SIZE * 0.85, "y": 0.0, "parkour": 0})
    if course[-1]["parkour"] == 0:
        course[-1]["y"] = 8.0; course[-1]["parkour"] = 1
    return {"map": MAP, "size": SIZE, "checkpoints": course}


if __name__ == "__main__":
    plan = design()
    root = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.abspath(os.path.join(root, "..", "engine_src", "data", "race_plan.json")), "w") as f:
        json.dump(plan, f, indent=2)

    hdr = os.path.abspath(os.path.join(root, "..", "engine_src", "exengine", "race_plan.h"))
    L = ["// AUTO-GENERATED by tools/gen_race.py from the openworld library. Do not edit.",
         "#ifndef RACE_PLAN_H", "#define RACE_PLAN_H", "",
         "typedef struct { float x, z, y; int parkour; } race_cp_t;", "",
         f'static const char *g_race_map = "{plan["map"]}";',
         f"#define NUM_RACE_CP {len(plan['checkpoints'])}",
         "static const race_cp_t g_race_course[NUM_RACE_CP] = {"]
    for c in plan["checkpoints"]:
        L.append(f"  {{ {c['x']:.1f}f, {c['z']:.1f}f, {c['y']:.1f}f, {c['parkour']} }},")
    L += ["};", "", "#endif"]
    with open(hdr, "w") as f:
        f.write("\n".join(L) + "\n")

    np = sum(c["parkour"] for c in plan["checkpoints"])
    print(f"RACE on {plan['map']}: {len(plan['checkpoints'])} checkpoints ({np} parkour gates)")
    print("wrote", hdr)
