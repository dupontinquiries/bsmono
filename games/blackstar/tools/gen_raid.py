"""gen_raid.py -- design a multi-phase RAID using the agnostic openworld library.

This is the plan's raid tier, authored offline with the library rather than hand-placed:
each phase is a palletted World; goal-setting drops the encounter POIs (objectives, a
boss); the optimiser tunes the arena; pathing lays the approach route. The result is a
raid_plan.json the in-game raid (next turn) will consume, so the level design is
data-driven and re-generatable.

Run: python3 tools/gen_raid.py
"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from openworld import build, patrol_tour, route_pois

# The deep-core raid: three escalating phases toward Unicron's heart.
PHASES = [
    {"name": "The Descent",   "palette": "void",   "seed": 101, "size": 110, "goals": 8},
    {"name": "The Gauntlet",  "palette": "frost",  "seed": 202, "size": 120, "goals": 10},
    {"name": "Unicron's Heart","palette": "ember", "seed": 303, "size": 95,  "goals": 6},
]


def design():
    raid = {"name": "Beneath the Pacific -- Raid", "phases": []}
    for i, ph in enumerate(PHASES):
        w = build(size=ph["size"], seed=ph["seed"], palette=ph["palette"],
                  goals=ph["goals"], optimize_iters=120)
        # the final phase forces a boss encounter as its centrepiece
        if i == len(PHASES) - 1 and not any(p.kind == "boss" for p in w.pois):
            w.pois[0].kind = "boss"
        tour = patrol_tour(w.world, start_xy=(0.0, -w.size * 0.8))
        route = route_pois(w.world, tour)
        encs = []
        for j, p in enumerate(tour):
            # Role MECHANIC from the substrate + position, so team comps matter:
            #   0 PURGE   -- any role; straightforward zone clear
            #   1 GROUND  -- an anti-air ceiling: flyers are forced DOWN, fight it grounded
            #   2 AIR     -- an elevated node: reach it by flying OR grapple/cable (ground gets creative)
            #   3 SYNC    -- needs >= min_units on the plates at once (forces a real team)
            h = w.height_at(p.x, p.y); rough = w.roughness_at(p.x, p.y)
            if p.kind == "boss":
                mech, mu = 0, 1
            elif h > 0.6:
                mech, mu = 2, 1            # high ground -> air node
            elif rough > 0.14:
                mech, mu = 1, 1            # broken/enclosed -> grounding field
            elif j % 3 == 1:
                mech, mu = 3, 3            # a sync plate set -> minimum THREE units
            else:
                mech, mu = 0, 1
            encs.append({"x": round(p.x, 1), "y": round(p.y, 1), "kind": p.kind,
                         "weight": p.weight, "mech": mech, "min_units": mu})
        raid["phases"].append({
            "name": ph["name"], "palette": ph["palette"], "size": ph["size"],
            "score": round(w.card.total, 1), "grade": w.card.grade(),
            "encounters": encs, "approach_waypoints": len(route),
        })
    return raid


if __name__ == "__main__":
    raid = design()
    data_dir = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine_src", "data"))
    out = os.path.join(data_dir, "raid_plan.json")
    with open(out, "w") as f:
        json.dump(raid, f, indent=2)
    print(f"RAID: {raid['name']}")
    for ph in raid["phases"]:
        kinds = {}
        for e in ph["encounters"]:
            kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
        print(f"  {ph['name']:22s} [{ph['palette']:7s}] score {ph['score']:.1f}{ph['grade']}  "
              f"encounters={len(ph['encounters'])} {kinds}  approach={ph['approach_waypoints']}wp")
    print("wrote", out)

    # --- bake a C header the in-game raid consumes (top encounters per phase) ---
    PAL_MAP = {"void": "kuiper", "frost": "frostline", "ember": "unicron",
               "verdant": "reclaim", "default": "cybertron"}
    KIND_ID = {"objective": 0, "boss": 1, "landmark": 2, "cache": 3, "spawn": 4}
    hdr = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine_src",
                       "exengine", "raid_plan.h")
    hdr = os.path.abspath(hdr)
    CAP = 4   # cap encounters per phase so the raid stays paced
    lines = ["// AUTO-GENERATED by tools/gen_raid.py from the openworld library. Do not edit.",
             "#ifndef RAID_PLAN_H", "#define RAID_PLAN_H", "",
             "// mech: 0 PURGE  1 GROUND(anti-air, flyers forced down)  2 AIR(elevated, fly/grapple)  3 SYNC(min_units on plates)",
             "typedef struct { float x, z; int kind; int mech; int min_units; } raid_enc_t;",
             "typedef struct { const char *name; const char *map; int n_enc; const raid_enc_t *enc; } raid_phase_t;",
             ""]
    phase_syms = []
    for i, ph in enumerate(raid["phases"]):
        # objectives (+boss) only, strongest first, capped
        encs = [e for e in ph["encounters"] if e["kind"] in ("objective", "boss")]
        encs.sort(key=lambda e: (e["kind"] != "boss", -e["weight"]))   # boss first, then by weight
        encs = encs[:CAP]
        sym = f"g_raid_enc_{i}"
        phase_syms.append((ph["name"], PAL_MAP.get(ph["palette"], "cybertron"), sym, len(encs)))
        lines.append(f"static const raid_enc_t {sym}[] = {{")
        for e in encs:
            lines.append(f"  {{ {e['x']:.1f}f, {e['y']:.1f}f, {KIND_ID.get(e['kind'],0)}, "
                         f"{e.get('mech',0)}, {e.get('min_units',1)} }},")
        lines.append("};")
    lines.append("")
    lines.append(f"#define NUM_RAID_PHASES {len(raid['phases'])}")
    lines.append("static const raid_phase_t g_raid_phases[NUM_RAID_PHASES] = {")
    for name, mp, sym, n in phase_syms:
        lines.append(f'  {{ "{name}", "{mp}", {n}, {sym} }},')
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    with open(hdr, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", hdr)
