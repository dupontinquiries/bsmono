  UNENDLICH_SHADOW_CHUNK_STRIDE=5 UNENDLICH_SHADOW_CACHE=1 UNENDLICH_SHADOW_MAP_SIZE=512 UNENDLICH_SHADOW_CULL_DIST=6
  UNENDLICH_GPU_MESHER=2 UNENDLICH_GPU_MESHER_MID=2 UNENDLICH_DEVICE_LOCAL_MESH=1
  UNENDLICH_ADAPTIVE_UPLOADS=1 UNENDLICH_SUBMIT_SKIP=1 UNENDLICH_SLACK_SCHEDULER=1
  UNENDLICH_BIASED_SHELL_WALK=1 UNENDLICH_UPLOAD_PRIORITY=1 UNENDLICH_REMESH_GATE=1
  UNENDLICH_APPLY_BUDGET=8 UNENDLICH_EVICT_BUDGET=8 UNENDLICH_SKY_CULL=1
  UNENDLICH_OCTREE_POOL_MB=6000
