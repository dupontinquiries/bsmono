#!/usr/bin/env bash
# run-latest.sh — unzip the highest-numbered unendlich release in this
# directory and run it with the standard perf env.
#
# Usage (from fable-wiring-journey/):
#   ./run-latest.sh              # unzip newest, build+run fullgame
#   ./run-latest.sh --list       # show what it would pick, newest last
#   ./run-latest.sh --release r169   # force a specific release
#   ./run-latest.sh --build-only     # cargo build, don't launch
#   ./run-latest.sh --suite "cargo test -p unendlich-engine"  # custom cmd
#   EXTRA_ENV="UNENDLICH_FOO=1" ./run-latest.sh  # append/override env
set -euo pipefail

cd "$(dirname "$0")"

# ── 1. pick the newest zip ──────────────────────────────────────────────
# Names look like: [anything--]unendlich-r<NUM>[letter]-<slug>-UNVERIFIED.zip
# Sort key: numeric release, then the optional letter suffix (b > a > none),
# so r157b beats r157 and r175 beats r133c.
pick_newest() {
  ls -1 *.zip 2>/dev/null \
    | grep -E 'unendlich-r[0-9]+[a-z]?-' \
    | awk '{
        s=$0
        match(s, /unendlich-r[0-9]+[a-z]?/)
        key=substr(s, RSTART+11, RLENGTH-11)       # e.g. "157b" or "175"
        num=key; suf=""
        if (key ~ /[a-z]$/) { suf=substr(key, length(key)); num=substr(key, 1, length(key)-1) }
        printf "%06d%s\t%s\n", num, (suf=="" ? "0" : suf), s
      }' \
    | sort \
    | cut -f2-
}

if [[ "${1:-}" == "--list" ]]; then
  pick_newest
  exit 0
fi

WANT=""
if [[ "${1:-}" == "--release" ]]; then
  WANT="${2:?usage: --release r169}"; shift 2
fi

if [[ -n "$WANT" ]]; then
  ZIP=$(ls -1 *.zip | grep -E "unendlich-${WANT}[a-z]?-" | head -1 || true)
  [[ -z "$ZIP" ]] && { echo "no zip matching ${WANT}" >&2; exit 1; }
else
  ZIP=$(pick_newest | tail -1)
  [[ -z "$ZIP" ]] && { echo "no unendlich-r*.zip here" >&2; exit 1; }
fi

DIR="${ZIP%.zip}"
echo ">> release: $ZIP"

# ── 2. unzip (idempotent: skip if already extracted) ────────────────────
if [[ -d "$DIR" && -f "$DIR/Cargo.toml" ]]; then
  echo ">> already extracted: $DIR"
else
  rm -rf "$DIR"
  mkdir -p "$DIR"
  # zips were built from inside the tree root, so extract INTO the dir
  unzip -q "$ZIP" -d "$DIR"
  echo ">> extracted -> $DIR"
fi

export TMP_DIR_UNEND="$PWD/$DIR"
cd "$TMP_DIR_UNEND/crates"
echo ">> cwd: $PWD"

# ── 3. the standard perf env (override/extend via EXTRA_ENV) ───────────
