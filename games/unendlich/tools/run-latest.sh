# r188: optional sccache — SCCACHE=1 ./run-latest.sh (install once with
# `cargo install sccache`). Cuts rebuild time across release zips since
# most crates are identical between releases.
if [[ "${SCCACHE:-0}" == "1" ]] && command -v sccache >/dev/null 2>&1; then
