#!/usr/bin/env python3
"""doc_linker.py — docs -> wiring-scratchpad linker.

For every design doc: extract TOP-K DISTINCTIVE TERMS (tf-idf vs the doc
corpus), then link each term into the code tree with a LINKER DEPTH:
  depth 0  filename / module name match        (system exists by name)
  depth 1  pub identifier match (fn/struct)    (API surface exists)
  depth 2  code-body match                     (mentioned in logic)
  depth 3  comment/doc-only match              (promised, not built)
  depth 4  NO match anywhere                   (missing — wiring target)

Outputs docs/DOC_LINKS.md:
  - per-doc PARITY SCORE (weighted by depth: how built is this doc?)
  - per-doc unlinked/most-shallow terms (the wiring backlog, ranked)
  - DOC<->DOC crossref graph (shared top-k terms = related docs)

Run: python3 tools/doc_linker.py [K]      (default K=18)
"""
import os, re, sys, math, collections

SRC = "crates/unendlich-engine/src"
DOCD = "docs/design"
OUT = "docs/DOC_LINKS.md"
K = int(sys.argv[1]) if len(sys.argv) > 1 else 18

STOP = set("""the a an and or of to in for with on by is are was were be been this
that these those it its as at from into over under not no if then else when
while can could should would may might must will shall do does did done have
has had you your we our they their he she them his her there here what which
who whom how why all any each every some most more less very just also only
than too via per each both between within without across after before during
section sections version note notes example examples player players game
world unendlich system systems design doc document reference v1 v2 mode""".split())

def words(text):
    return [w for w in re.findall(r"[a-z][a-z_0-9]{3,}", text.lower()) if w not in STOP]

# ── corpus ──────────────────────────────────────────────────────────────
docs = {}
for f in sorted(os.listdir(DOCD)):
    if f.endswith(".extracted.md") or (f.endswith(".md") and not f.endswith(".extracted.md")):
        docs[f] = open(os.path.join(DOCD, f), encoding="utf-8", errors="replace").read()
N = len(docs)
tf = {d: collections.Counter(words(t)) for d, t in docs.items()}
df = collections.Counter()
for d, c in tf.items():
    for w in c:
        df[w] += 1

topk = {}
for d, c in tf.items():
    scored = sorted(
        ((cnt * math.log(1 + N / df[w]), w) for w, cnt in c.items() if cnt >= 2),
        reverse=True,
    )
    topk[d] = [w for _, w in scored[:K]]

# ── code index (built once) ─────────────────────────────────────────────
file_names = {}
pub_idents = collections.defaultdict(set)   # word -> files
code_words = collections.defaultdict(set)
comment_words = collections.defaultdict(set)
for dp, dn, fns in os.walk(SRC):
    if "target" in dp: continue
    for fn in fns:
        if not fn.endswith(".rs") and not fn.endswith(".comp") and not fn.endswith(".frag"):
            continue
        p = os.path.join(dp, fn)
        stem = fn.rsplit(".", 1)[0].lower()
        for piece in re.split(r"[_]", stem):
            if len(piece) > 3:
                file_names.setdefault(piece, set()).add(p)
        file_names.setdefault(stem, set()).add(p)
        t = open(p, encoding="utf-8", errors="replace").read()
        comments = " ".join(re.findall(r"//[^\n]*", t)).lower()
        body = re.sub(r"//[^\n]*", "", t).lower()
        for m in re.finditer(r"pub (?:fn|struct|enum|trait) (\w+)", t):
            for piece in re.split(r"_", m.group(1).lower()):
                if len(piece) > 3:
                    pub_idents[piece].add(p)
        for w in set(re.findall(r"[a-z][a-z_0-9]{3,}", body)):
            code_words[w].add(p)
        for w in set(re.findall(r"[a-z][a-z_0-9]{3,}", comments)):
            comment_words[w].add(p)

def link(term):
    if term in file_names: return 0, sorted(file_names[term])[:3]
    if term in pub_idents: return 1, sorted(pub_idents[term])[:3]
    if term in code_words: return 2, sorted(code_words[term])[:3]
    if term in comment_words: return 3, sorted(comment_words[term])[:3]
    return 4, []

# ── emit ────────────────────────────────────────────────────────────────
lines = ["# DOC LINKS — docs -> code parity (generated by tools/doc_linker.py)",
         f"# corpus: {N} docs, top-{K} distinctive terms each. depth: 0=file",
         "# 1=pub-ident 2=code 3=comment-only 4=MISSING. Low parity = wiring target.", ""]
parity_rank = []
crossref_terms = collections.defaultdict(set)
for d in sorted(docs):
    terms = topk[d]
    linked = [(term, *link(term)) for term in terms]
    score = sum(4 - depth for term, depth, _ in linked) / max(1, 4 * len(linked))
    parity_rank.append((score, d))
    for term in terms:
        crossref_terms[term].add(d)
    lines.append(f"## {d}  (parity {score:.0%})")
    for term, depth, files in linked:
        tag = ["FILE", "PUB ", "code", "cmnt", "MISS"][depth]
        loc = files[0] if files else "-"
        lines.append(f"  [{tag}] {term:<22} {loc}")
    lines.append("")

lines.append("## PARITY RANKING (lowest = biggest doc->code gap = wire next)")
for score, d in sorted(parity_rank):
    lines.append(f"  {score:.0%}  {d}")
lines.append("")
lines.append("## DOC<->DOC CROSSREF (shared distinctive terms)")
pair = collections.Counter()
for term, ds in crossref_terms.items():
    ds = sorted(ds)
    for i in range(len(ds)):
        for j in range(i + 1, len(ds)):
            pair[(ds[i], ds[j])] += 1
for (a, b), n in pair.most_common(14):
    if n >= 2:
        lines.append(f"  {n:>2} shared  {a}  <->  {b}")
open(OUT, "w").write("\n".join(lines))
print(f"-> {OUT}")
for score, d in sorted(parity_rank):
    print(f"  {score:.0%}  {d}")
