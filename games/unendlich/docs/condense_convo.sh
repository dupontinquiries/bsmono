#!/usr/bin/env bash
# condense_convo.sh
#
# Compresses a claude.ai conversation transcript down to:
#   - the user's messages in full
#   - Claude's first paragraph per response (the "lede")
#   - tool-use noise stripped
#
# Tested against transcripts of the form produced by claude.ai's
# "copy conversation" feature, which yields:
#   You said: ...
#   <date marker>
#   Claude responded: <first sentence>
#   <first sentence repeated as paragraph>
#   <body of response>
#   Ran N commands[, edited a file][, created a file]
#   ...
#   You said: ...
#
# Usage:
#   ./condense_convo.sh INPUT.txt OUTPUT.txt
#
# The output is roughly 5-15% the size of the input depending on how
# much tool use vs. prose was in the original.

set -euo pipefail

if [[ $# -ne 2 ]]; then
    echo "usage: $0 INPUT.txt OUTPUT.txt" >&2
    exit 1
fi

IN="$1"
OUT="$2"

if [[ ! -f "$IN" ]]; then
    echo "input file not found: $IN" >&2
    exit 1
fi

# awk does the heavy lifting because we need stateful parsing
# (track which "section" we're in across many lines).
awk '
BEGIN {
    state = "header"        # header | user | claude_lede | claude_body
    claude_lede_lines = 0
    print "# Conversation summary"
    print "# Generated by condense_convo.sh"
    print "# Format: user messages in full, Claude responses summarized"
    print "# to the first ~3 lines (the lede). Tool use stripped."
    print ""
}

# Date markers like "Jan 30" or "May 6" — drop entirely
/^[A-Z][a-z]+ [0-9]+$/ { next }

# Tool-use chatter — drop entirely
/^Ran [0-9]+ command/    { next }
/^Viewed [0-9]+ file/    { next }
/^Read [0-9]+ file/      { next }
/^Edited a file$/        { next }
/^Created a file$/       { next }
/^Created [0-9]+ file/   { next }
/^Edited [0-9]+ file/    { next }

# Markers for tool-call titles claude.ai inserts
# (e.g. "Check version", "Bump to 0.17.1") — these show up as
# standalone short lines between command runs. Heuristic: if a line
# is short and Title Case and we are in claude_body mode, skip it
# only if the very next non-blank line is a "Ran ..." or similar.
# Without a lookahead this is hard; we accept some noise.

# User turn begins
/^You said:/ {
    if (claude_buf_count > 0) flush_claude()
    if (user_buf_count > 0) flush_user()
    state = "user"
    sub(/^You said: */, "")
    print ""
    print "## User"
    print ""
    if (length($0) > 0) {
        user_buf[user_buf_count++] = $0
    }
    next
}

function flush_user(    i, keep) {
    # Same dedup logic: if line i+1 starts with line i, drop line i.
    for (i = 0; i < user_buf_count; i++) keep[i] = 1
    for (i = 0; i < user_buf_count - 1; i++) {
        if (substr(user_buf[i+1], 1, length(user_buf[i])) == user_buf[i]) {
            keep[i] = 0
        }
    }
    for (i = 0; i < user_buf_count; i++) {
        if (keep[i]) print user_buf[i]
    }
    user_buf_count = 0
}

# Claude turn begins
/^Claude responded:/ {
    if (claude_buf_count > 0) flush_claude()
    if (user_buf_count > 0) flush_user()
    state = "claude_lede"
    claude_buf_count = 0
    sub(/^Claude responded: */, "")
    print ""
    print "## Claude"
    print ""
    if (length($0) > 0) {
        claude_buf[claude_buf_count++] = $0
    }
    next
}

function flush_claude(    i, j, keep) {
    # Dedup: if line i+1 starts with line i, drop line i (it was the
    # truncated preview; the next line is the full version).
    keep[0] = 1
    for (i = 0; i < claude_buf_count; i++) keep[i] = 1
    for (i = 0; i < claude_buf_count - 1; i++) {
        if (substr(claude_buf[i+1], 1, length(claude_buf[i])) == claude_buf[i]) {
            keep[i] = 0
        }
    }
    for (i = 0; i < claude_buf_count; i++) {
        if (keep[i]) print claude_buf[i]
    }
    claude_buf_count = 0
}

# Body lines
{
    if (state == "user") {
        if (length($0) > 0) {
            user_buf[user_buf_count++] = $0
        } else if (user_buf_count > 0 && user_buf[user_buf_count-1] != "") {
            user_buf[user_buf_count++] = ""
        }
    } else if (state == "claude_lede") {
        # Buffer first ~3 non-blank lines as the lede; flush at next turn
        if (length($0) > 0) {
            if (claude_buf_count < 3) {
                claude_buf[claude_buf_count++] = $0
            } else {
                state = "claude_body"
            }
        }
    }
    # state == claude_body: drop everything
    # state == header: drop everything before first turn
}

END {
    if (claude_buf_count > 0) flush_claude()
    if (user_buf_count > 0) flush_user()
}
' "$IN" > "$OUT"

# Report sizes
in_lines=$(wc -l < "$IN")
out_lines=$(wc -l < "$OUT")
in_bytes=$(wc -c < "$IN")
out_bytes=$(wc -c < "$OUT")
ratio=$(awk -v a="$out_bytes" -v b="$in_bytes" 'BEGIN { printf "%.1f", (a/b)*100 }')

echo "input:  $in_lines lines, $in_bytes bytes" >&2
echo "output: $out_lines lines, $out_bytes bytes" >&2
echo "ratio:  ${ratio}%" >&2
