# The active palette (matches the other apps' default). Change to restyle paperbound's UI.
ACTIVE = "paper"  # paperbound's notebook aesthetic; the kit's matching palette


def color(field: str, palette: str | None = None) -> tuple[int, int, int]:
    """A palette color as a pygame (r,g,b) tuple, e.g. color('accent'), color('bg_base')."""
    p = PALETTES[palette or ACTIVE]
    return rgb(p[field])


