"""
PAPERBOUND — theme.

The portfolio's colors live once in the Rust crate shared/uikit/crates/snapclone-theme (read by the
egui/Qt/web backends). Paperbound is pygame, so it can't depend on that crate — instead this module
MIRRORS it: it was generated from palette.rs, so paperbound draws from the same palette as every other
app. Regenerate if the palette changes. `rgb()` parses the shared #RRGGBB hex to a pygame-ready tuple.
"""
from __future__ import annotations


def rgb(hex_str: str) -> tuple[int, int, int]:
    """Parse a shared '#RRGGBB' token to an (r, g, b) tuple (mirrors snapclone_theme::rgb)."""
    h = hex_str.lstrip("#")
    if len(h) < 6:
        return (255, 0, 255)
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


