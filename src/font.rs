/// Draw `s` with its top-left corner at NDC (x, y). `px` is the pixel size in
/// NDC-y units; `aspect` keeps pixels square. Returns the NDC width consumed.
pub fn text(ui: &mut Vec<UiVert>, x: f32, y: f32, px: f32, aspect: f32, color: [f32; 4], s: &str) -> f32 {
    let pw = px / aspect;
    let mut cx = x;
    for ch in s.chars() {
        let up = ch.to_ascii_uppercase();
        if let Some(rows) = glyph(up) {
            for (ry, row) in rows.iter().enumerate() {
                for (rx, cell) in row.bytes().enumerate() {
                    if cell == b'#' {
                        let x0 = cx + rx as f32 * pw;
                        let y0 = y - ry as f32 * px;
                        let v = |x: f32, y: f32| UiVert { pos: [x, y], color };
                        ui.extend_from_slice(&[
                            v(x0, y0),
                            v(x0 + pw, y0),
                            v(x0 + pw, y0 - px),
                            v(x0, y0),
                            v(x0 + pw, y0 - px),
                            v(x0, y0 - px),
                        ]);
                    }
                }
            }
        }
        cx += CW * pw;
    }
    cx - x
}

/// NDC width of `s` at pixel size `px`.
pub fn width(s: &str, px: f32, aspect: f32) -> f32 {
    s.chars().count() as f32 * CW * px / aspect
}

/// Convenience: horizontally centered text at NDC height y.
#[allow(dead_code)] // hud switched to shadowed label_c; kept as public API
pub fn text_centered(ui: &mut Vec<UiVert>, y: f32, px: f32, aspect: f32, color: [f32; 4], s: &str) {
    let w = width(s, px, aspect);
    text(ui, -w * 0.5, y, px, aspect, color, s);
}
